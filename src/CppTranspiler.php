struct PyScope {
    std::unordered_map<std::string, Val> vars;
    PyScope* parent = nullptr;
    explicit PyScope(PyScope* p = nullptr) : parent(p) {}
    bool has(const std::string& n) const {
        for (const PyScope* e = this; e; e = e->parent) { if (e->vars.count(n)) return true; }
        return false;
    }
    const Val& get(const std::string& n) const {
        for (const PyScope* e = this; e; e = e->parent) {
            auto it = e->vars.find(n);
            if (it != e->vars.end()) return it->second;
        }
        pyhp_rt_throw("RuntimeError", "undefined variable '" + n + "'");
        static Val dummy;
        return dummy;
    }
    void declare(const std::string& n, Val v) { vars[n] = std::move(v); }
    void assign(const std::string& n, Val v) {
        for (PyScope* e = this; e; e = e->parent) {
            auto it = e->vars.find(n);
            if (it != e->vars.end()) { it->second = std::move(v); return; }
        }
        vars[n] = std::move(v);
    }
};


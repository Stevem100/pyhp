static std::string pyhp_rt_type_name(const Val& v) {
    switch (v.k) {
        case Val::NUL: return "null";
        case Val::IN:  return "int";
        case Val::FL:  return "float";
        case Val::ST:  return "string";
        case Val::BO:  return "bool";
        case Val::LI:  return "list";
        case Val::DI:  return "dict";
        case Val::FN:  return "function";
        case Val::ER:  return v.et;
    }
    return "unknown";
}

static bool pyhp_rt_is_num(const Val& v) { return v.k == Val::IN || v.k == Val::FL || v.k == Val::BO; }
static int64_t pyhp_rt_as_int(const Val& v) { return v.k == Val::BO ? (int64_t)(v.b ? 1 : 0) : v.i; }

static bool pyhp_rt_truthy(const Val& v) {
    switch (v.k) {
        case Val::NUL: return false;
        case Val::BO: return v.b;
        case Val::IN: return v.i != 0;
        case Val::FL: return v.f != 0.0;
        case Val::ST: return !v.s->empty();
        case Val::LI: return !v.li->empty();
        case Val::DI: return !v.di->empty();
        default: return true;
    }
}

static std::string pyhp_rt_num_str(double v) {
    if (std::isinf(v)) return v > 0 ? "inf" : "-inf";
    if (std::isnan(v)) return "nan";
    char buf[64];
    std::snprintf(buf, sizeof(buf), "%.14G", v);
    std::string r(buf);
    size_t e = r.find_first_of("eE");
    std::string mant = (e == std::string::npos) ? r : r.substr(0, e);
    std::string exp = (e == std::string::npos) ? std::string() : r.substr(e);
    if (mant.find('.') == std::string::npos) mant += ".0";
    if (!exp.empty()) {
        // PHP prints exponents with minimal digits: 1E-9 not 1E-09
        std::string sign;
        size_t d = 1;
        if (exp.size() > 1 && (exp[1] == '+' || exp[1] == '-')) { sign = exp[1]; d = 2; }
        std::string digits = exp.substr(d);
        size_t nz = digits.find_first_not_of('0');
        if (nz == std::string::npos) digits = "0";
        else digits = digits.substr(nz);
        exp = exp[0] + sign + digits;
    }
    return mant + exp;
}

static std::string pyhp_rt_repr_str(const std::string& s) {
    std::string out = "'";
    for (char c : s) {
        switch (c) {
            case '\\': out += "\\\\"; break;
            case '\'': out += "\\'"; break;
            case '\n': out += "\\n"; break;
            case '\t': out += "\\t"; break;
            case '\r': out += "\\r"; break;
            case '\0': out += "\\0"; break;
            default: out += c;
        }
    }
    return out + "'";
}

static std::string pyhp_rt_repr(const Val& v);
static Val pyhp_rt_key_decode(const std::string& k);
static std::string pyhp_rt_tostr(const Val& v) {
    switch (v.k) {
        case Val::NUL: return "null";
        case Val::BO: return v.b ? "true" : "false";
        case Val::IN: return std::to_string(v.i);
        case Val::FL: return pyhp_rt_num_str(v.f);
        case Val::ST: return *v.s;
        case Val::LI: {
            std::string out = "[";
            bool first = true;
            for (const Val& x : *v.li) {
                if (!first) out += ", ";
                first = false;
                out += pyhp_rt_repr(x);
            }
            return out + "]";
        }
        case Val::DI: {
            std::string out = "{";
            bool first = true;
            for (const auto& kv : *v.di) {
                if (!first) out += ", ";
                first = false;
                out += pyhp_rt_repr(pyhp_rt_key_decode(kv.first)) + ": " + pyhp_rt_repr(kv.second);
            }
            return out + "}";
        }
        case Val::FN: return "<function " + v.et + ">";
        case Val::ER: return *v.s;
    }
    return "unknown";
}

/* ---------------- f-string format specs (mirror of pyhp_format) -------- */
static std::string pyhp_rt_group_digits(const std::string& d) {
    std::string out; int c = 0;
    for (size_t i = d.size(); i-- > 0;) {
        out += d[i];
        if (++c % 3 == 0 && i > 0 && isdigit((unsigned char)d[i - 1])) out += ',';
    }
    std::reverse(out.begin(), out.end());
    return out;
}

static std::string pyhp_rt_fix_exp(std::string s) {
    for (size_t i = 0; i + 2 < s.size(); i++) {
        if ((s[i] == 'e' || s[i] == 'E') && (s[i+1] == '+' || s[i+1] == '-') && isdigit((unsigned char)s[i+2])) {
            if (i + 3 >= s.size() || !isdigit((unsigned char)s[i+3])) s.insert(i + 2, 1, '0');
        }
    }
    return s;
}

static std::string pyhp_rt_utf8_chr(int cp) {
    std::string o;
    if (cp < 0x80) o += (char)cp;
    else if (cp < 0x800) { o += (char)(0xC0 | (cp >> 6)); o += (char)(0x80 | (cp & 0x3F)); }
    else if (cp < 0x10000) { o += (char)(0xE0 | (cp >> 12)); o += (char)(0x80 | ((cp >> 6) & 0x3F)); o += (char)(0x80 | (cp & 0x3F)); }
    else { o += (char)(0xF0 | (cp >> 18)); o += (char)(0x80 | ((cp >> 12) & 0x3F)); o += (char)(0x80 | ((cp >> 6) & 0x3F)); o += (char)(0x80 | (cp & 0x3F)); }
    return o;
}

static std::string pyhp_rt_format_g(double v, int p, bool lower) {
    if (std::isinf(v) || std::isnan(v)) {
        std::string s = v > 0 ? "inf" : (std::isnan(v) ? "nan" : "-inf");
        if (!lower) for (auto& c : s) c = (char)toupper((unsigned char)c);
        return s;
    }
    if (v == 0.0) return "0";
    int exp = (int)std::floor(std::log10(std::fabs(v)));
    if (exp < -4 || exp >= p) {
        char buf[64];
        std::snprintf(buf, sizeof(buf), "%.*e", p - 1, v);
        std::string body(buf);
        if (!lower) for (auto& c : body) if (c == 'e') c = 'E';
        size_t e = body.find(lower ? 'e' : 'E');
        std::string mant = body.substr(0, e);
        size_t last = mant.find_last_not_of('0');
        if (last != std::string::npos && mant[last] == '.') last--;
        mant = mant.substr(0, last + 1);
        return mant + body.substr(e);
    }
    char buf[64];
    std::snprintf(buf, sizeof(buf), "%.*f", std::max(0, p - 1 - exp), v);
    std::string body(buf);
    if (body.find('.') != std::string::npos) {
        size_t last = body.find_last_not_of('0');
        if (last != std::string::npos && body[last] == '.') last--;
        body = body.substr(0, last + 1);
    }
    return body;
}

static std::string pyhp_rt_pad(const std::string& s, long width, char fill, char align) {
    if (width <= (long)s.size()) return s;
    long total = width - (long)s.size();
    if (align == '>') { std::string p; for (long i = 0; i < total; i++) p += fill; return p + s; }
    if (align == '<') { std::string p; for (long i = 0; i < total; i++) p += fill; return s + p; }
    long left = total / 2, right = total - left;
    std::string pl, pr;
    for (long i = 0; i < left; i++) pl += fill;
    for (long i = 0; i < right; i++) pr += fill;
    return pl + s + pr;
}

static std::string pyhp_rt_format(const Val& v, const std::string& spec) {
    size_t p = 0;
    char fill = ' ', align = 0;
    if (spec.size() >= 2 && (spec[1] == '<' || spec[1] == '>' || spec[1] == '^')) { fill = spec[0]; align = spec[1]; p = 2; }
    else if (!spec.empty() && (spec[0] == '<' || spec[0] == '>' || spec[0] == '^')) { align = spec[0]; p = 1; }
    char signC = '-';
    if (p < spec.size() && (spec[p] == '+' || spec[p] == '-' || spec[p] == ' ')) signC = spec[p++];
    bool alt = false;
    if (p < spec.size() && spec[p] == '#') { alt = true; p++; }
    bool zero = false;
    if (p < spec.size() && spec[p] == '0') { zero = true; p++; }
    long width = 0; bool grp = false;
    size_t ws = p;
    while (p < spec.size() && (isdigit((unsigned char)spec[p]) || spec[p] == ',')) p++;
    if (p > ws) {
        std::string w = spec.substr(ws, p - ws);
        grp = w.find(',') != std::string::npos;
        w.erase(std::remove(w.begin(), w.end(), ','), w.end());
        if (!w.empty()) width = std::atoll(w.c_str());
    }
    int prec = -1;
    if (p < spec.size() && spec[p] == '.') {
        p++; prec = 0;
        while (p < spec.size() && isdigit((unsigned char)spec[p])) { prec = prec * 10 + (spec[p] - '0'); p++; }
    }
    char type = 0;
    if (p < spec.size()) type = spec[p++];
    if (p != spec.size()) pyhp_rt_throw("Error", "invalid format spec '" + spec + "'");

    std::string body;
    bool strish = (type == 's' || type == 'c' || (type == 0 && v.k != Val::IN && v.k != Val::FL));
    if (strish) {
        if (type == 'c') {
            if (v.k == Val::IN) {
                int64_t cp = v.i;
                if (cp < 0 || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) pyhp_rt_throw("Error", "invalid code point for format type c");
                body = pyhp_rt_utf8_chr((int)cp);
            } else {
                std::string s = pyhp_rt_tostr(v);
                if (s.empty()) pyhp_rt_throw("Error", "cannot format an empty string with type c");
                body = s.substr(0, 1);
            }
        } else {
            body = pyhp_rt_tostr(v);
            if (prec >= 0 && (type == 's' || type == 0) && (size_t)prec < body.size()) body = body.substr(0, prec);
        }
        if (align == 0) align = '<';
    } else {
        if (v.k != Val::IN && v.k != Val::FL && v.k != Val::BO) pyhp_rt_throw("TypeError", "unsupported value for format spec '" + spec + "'");
        double f = v.k == Val::IN ? (double)v.i : (v.k == Val::BO ? (v.b ? 1.0 : 0.0) : v.f);
        double af = std::fabs(f);
        bool neg = f < 0 || (f == 0 && pyhp_rt_num_str(f)[0] == '-');
        std::string prefix;
        if (type == 'd' || (type == 0 && v.k == Val::IN)) {
            if (v.k == Val::FL) pyhp_rt_throw("TypeError", "unknown format code 'd' for float — use :f or :g");
            body = std::to_string(v.i < 0 ? -v.i : v.i);
        } else if (type == 'b' || type == 'o' || type == 'x' || type == 'X') {
            if (grp) pyhp_rt_throw("Error", std::string("cannot use ',' with format type '") + type + "'");
            unsigned long long u = (unsigned long long)llround(std::fabs(v.k == Val::IN ? (double)v.i : f));
            char buf[80];
            if (type == 'b') {
                std::string d;
                if (u == 0) d = "0";
                while (u) { d += (char)('0' + (u & 1ULL)); u >>= 1; }
                std::reverse(d.begin(), d.end());
                body = d;
            } else if (type == 'o') { std::snprintf(buf, sizeof(buf), "%llo", u); body = buf; }
            else if (type == 'x') { std::snprintf(buf, sizeof(buf), "%llx", u); body = buf; }
            else { std::snprintf(buf, sizeof(buf), "%llX", u); body = buf; }
            if (alt) prefix = type == 'b' ? "0b" : (type == 'o' ? "0o" : (type == 'X' ? "0X" : "0x"));
        } else if (type == 'f' || type == 'F') {
            char buf[512];
            std::snprintf(buf, sizeof(buf), "%.*f", prec < 0 ? 6 : prec, af);
            body = buf;
            if (type == 'f' && (body.find("INF") != std::string::npos || body.find("NAN") != std::string::npos)) {
                for (auto& c : body) c = (char)tolower((unsigned char)c);
            }
        } else if (type == 'e' || type == 'E') {
            char buf[512];
            std::snprintf(buf, sizeof(buf), "%.*e", prec < 0 ? 6 : prec, af);
            body = buf;
            char want = type == 'e' ? 'e' : 'E', other = type == 'e' ? 'E' : 'e';
            for (auto& c : body) if (c == other) c = want;
        } else if (type == 'g' || type == 'G' || (type == 0 && v.k == Val::FL && prec >= 0)) {
            body = pyhp_rt_format_g(af, prec < 0 ? 6 : std::max(1, prec), type != 'G');
            if (type == 'G') for (auto& c : body) c = (char)toupper((unsigned char)c);
        } else if (type == '%') {
            char buf[512];
            std::snprintf(buf, sizeof(buf), "%.*f", prec < 0 ? 6 : prec, af * 100.0);
            body = std::string(buf) + "%";
        } else {
            body = pyhp_rt_num_str(af);
        }
        std::string signStr = neg ? "-" : (signC == '+' ? "+" : (signC == ' ' ? " " : ""));
        if (zero && align == 0 && width > 0) {
            size_t dr = 0;
            while (dr < body.size() && isdigit((unsigned char)body[dr])) dr++;
            long avail = width - (long)signStr.size() - (long)prefix.size() - (long)(body.size() - dr);
            if ((long)dr < avail) body.insert(0, (size_t)(avail - dr), '0');
        }
        if (grp) {
            size_t dr = 0;
            while (dr < body.size() && isdigit((unsigned char)body[dr])) dr++;
            body = pyhp_rt_group_digits(body.substr(0, dr)) + body.substr(dr);
        }
        body = signStr + prefix + body;
        if (align == 0) align = '>';
    }
    if (width > 0 && (long)body.size() < width) body = pyhp_rt_pad(body, width, fill, align);
    return body;
}
static std::string pyhp_rt_repr(const Val& v) {
    if (v.k == Val::ST) return pyhp_rt_repr_str(*v.s);
    return pyhp_rt_tostr(v);
}

/* dict key encoding: int keys get a \x01 marker so 1 and "1" stay distinct */
static std::string pyhp_rt_key_encode(const Val& k) {
    if (k.k == Val::IN) return std::string("\x01", 1) + std::to_string(k.i);
    if (k.k == Val::ST) return *k.s;
    pyhp_rt_throw("TypeError", "dict keys must be int or string, got " + pyhp_rt_type_name(k));
    return "";
}
static Val pyhp_rt_key_decode(const std::string& k) {
    if (!k.empty() && k[0] == '\x01') return Val::mk((int64_t)std::strtoll(k.c_str() + 1, nullptr, 10));
    return Val::mk(k);
}

static Val pyhp_rt_list(std::vector<Val> items) {
    Val v = Val::mklist();
    v.li->assign(items.begin(), items.end());
    return v;
}
static Val pyhp_rt_dict(std::vector<std::pair<std::string, Val>> pairs) {
    Val v = Val::mkdict();
    for (auto& p : pairs) v.di->push_back(std::move(p));
    return v;
}

/* ---------------- arithmetic ---------------- */
static Val pyhp_rt_add(const Val& a, const Val& b) {
    if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
        if (a.k == Val::IN && b.k == Val::IN) return Val::mk((int64_t)(a.i + b.i));
        return Val::mk((a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a)) + (b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b)));
    }
    if (a.k == Val::ST || b.k == Val::ST) return Val::mk(pyhp_rt_tostr(a) + pyhp_rt_tostr(b));
    if (a.k == Val::LI && b.k == Val::LI) {
        Val out = Val::mklist();
        out.li->insert(out.li->end(), a.li->begin(), a.li->end());
        out.li->insert(out.li->end(), b.li->begin(), b.li->end());
        return out;
    }
    if (a.k == Val::DI && b.k == Val::DI) {
        Val out = Val::mkdict();
        *out.di = *a.di;
        for (const auto& p : *b.di) {
            bool replaced = false;
            for (auto& q : *out.di) { if (q.first == p.first) { q.second = p.second; replaced = true; break; } }
            if (!replaced) out.di->push_back(p);
        }
        return out;
    }
    pyhp_rt_throw("TypeError", "unsupported operand type(s) for +: '" + pyhp_rt_type_name(a) + "' and '" + pyhp_rt_type_name(b) + "'");
    return Val::nul();
}
static Val pyhp_rt_sub(const Val& a, const Val& b) {
    if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
        if (a.k == Val::IN && b.k == Val::IN) return Val::mk((int64_t)(a.i - b.i));
        return Val::mk((a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a)) - (b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b)));
    }
    pyhp_rt_throw("TypeError", "unsupported operand type(s) for -: '" + pyhp_rt_type_name(a) + "' and '" + pyhp_rt_type_name(b) + "'");
    return Val::nul();
}
static Val pyhp_rt_mul(const Val& a, const Val& b) {
    if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
        if (a.k == Val::IN && b.k == Val::IN) return Val::mk((int64_t)(a.i * b.i));
        return Val::mk((a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a)) * (b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b)));
    }
    if (a.k == Val::ST && pyhp_rt_is_num(b)) {
        std::string out;
        for (int64_t n = pyhp_rt_as_int(b); n > 0; n--) out += *a.s;
        return Val::mk(out);
    }
    if (pyhp_rt_is_num(a) && b.k == Val::ST) {
        std::string out;
        for (int64_t n = pyhp_rt_as_int(a); n > 0; n--) out += *b.s;
        return Val::mk(out);
    }
    if (a.k == Val::LI && pyhp_rt_is_num(b)) {
        Val out = Val::mklist();
        for (int64_t n = pyhp_rt_as_int(b); n > 0; n--) out.li->insert(out.li->end(), a.li->begin(), a.li->end());
        return out;
    }
    if (pyhp_rt_is_num(a) && b.k == Val::LI) return pyhp_rt_mul(b, a);
    pyhp_rt_throw("TypeError", "unsupported operand type(s) for *: '" + pyhp_rt_type_name(a) + "' and '" + pyhp_rt_type_name(b) + "'");
    return Val::nul();
}
static Val pyhp_rt_div(const Val& a, const Val& b) {
    if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
        double x = a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a);
        double y = b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b);
        if (y == 0) pyhp_rt_throw("ZeroDivisionError", "division by zero");
        // PHP: int/int evenly divisible stays int (list indexing relies on it)
        if (a.k == Val::IN && b.k == Val::IN && b.i != 0 && a.i % b.i == 0) return Val::mk((int64_t)(a.i / b.i));
        return Val::mk(x / y);
    }
    pyhp_rt_throw("TypeError", "unsupported operand type(s) for /: '" + pyhp_rt_type_name(a) + "' and '" + pyhp_rt_type_name(b) + "'");
    return Val::nul();
}
static Val pyhp_rt_mod(const Val& a, const Val& b) {
    if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
        if (a.k == Val::IN && b.k == Val::IN) {
            if (b.i == 0) pyhp_rt_throw("ZeroDivisionError", "modulo by zero");
            int64_t r = a.i % b.i;
            if (r != 0 && ((r < 0) != (b.i < 0))) r += b.i;
            return Val::mk(r);
        }
        double x = a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a);
        double y = b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b);
        if (y == 0) pyhp_rt_throw("ZeroDivisionError", "modulo by zero");
        double r = x - y * std::floor(x / y);
        return Val::mk(r);
    }
    pyhp_rt_throw("TypeError", "unsupported operand type(s) for %: '" + pyhp_rt_type_name(a) + "' and '" + pyhp_rt_type_name(b) + "'");
    return Val::nul();
}
static Val pyhp_rt_pow(const Val& a, const Val& b) {
    if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
        if (a.k == Val::IN && b.k == Val::IN && b.i >= 0) {
            int64_t out = 1, base = a.i, e = b.i;
            while (e > 0) { if (e & 1) out *= base; base *= base; e >>= 1; }
            return Val::mk(out);
        }
        double x = a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a);
        double y = b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b);
        return Val::mk(std::pow(x, y));
    }
    pyhp_rt_throw("TypeError", "unsupported operand type(s) for **: '" + pyhp_rt_type_name(a) + "' and '" + pyhp_rt_type_name(b) + "'");
    return Val::nul();
}
static int64_t pyhp_rt_bit_int(const Val& v, const char* op) {
    if (v.k == Val::IN) return v.i;
    if (v.k == Val::BO) return v.b ? 1 : 0;
    pyhp_rt_throw("TypeError", std::string("bitwise ") + op + " requires int operands, got '" + pyhp_rt_type_name(v) + "'");
    return 0;
}
static Val pyhp_rt_bitand(const Val& a, const Val& b) { return Val::mk(pyhp_rt_bit_int(a, "AND (&)") & pyhp_rt_bit_int(b, "AND (&)")); }
static Val pyhp_rt_bitor (const Val& a, const Val& b) { return Val::mk(pyhp_rt_bit_int(a, "OR (|)")  | pyhp_rt_bit_int(b, "OR (|)")); }
static Val pyhp_rt_bitxor(const Val& a, const Val& b) { return Val::mk(pyhp_rt_bit_int(a, "XOR (^)") ^ pyhp_rt_bit_int(b, "XOR (^)")); }
static Val pyhp_rt_lshift(const Val& a, const Val& b) {
    int64_t n = pyhp_rt_bit_int(b, "shift (<<)");
    if (n < 0) pyhp_rt_throw("ValueError", "negative shift count");
    return Val::mk((int64_t)(pyhp_rt_bit_int(a, "shift (<<)") << n));
}
static Val pyhp_rt_rshift(const Val& a, const Val& b) {
    int64_t n = pyhp_rt_bit_int(b, "shift (>>)");
    if (n < 0) pyhp_rt_throw("ValueError", "negative shift count");
    return Val::mk((int64_t)(pyhp_rt_bit_int(a, "shift (>>)") >> n));
}
static Val pyhp_rt_bitnot(const Val& a) { return Val::mk((int64_t)(~pyhp_rt_bit_int(a, "NOT (~)"))); }
static Val pyhp_rt_neg(const Val& a) {
    if (a.k == Val::IN) return Val::mk((int64_t)-a.i);
    if (a.k == Val::FL) return Val::mk(-a.f);
    if (a.k == Val::BO) return Val::mk((int64_t)-(a.b ? 1 : 0));
    pyhp_rt_throw("TypeError", "bad operand type for unary -: '" + pyhp_rt_type_name(a) + "'");
    return Val::nul();
}
static Val pyhp_rt_not(const Val& a) { return Val::mk(!pyhp_rt_truthy(a)); }
static Val pyhp_rt_inc(const Val& v, int dir) {
    if (v.k == Val::IN) return Val::mk((int64_t)(v.i + dir));
    if (v.k == Val::FL) return Val::mk(v.f + dir);
    if (v.k == Val::BO) return Val::mk((int64_t)((v.b ? 1 : 0) + dir));
    pyhp_rt_throw("TypeError", std::string("'++'/'--' requires a numeric variable, got ") + pyhp_rt_type_name(v));
    return Val::nul();
}

static bool pyhp_rt_eq(const Val& a, const Val& b);
static bool pyhp_rt_eq(const Val& a, const Val& b) {
    if (a.k == Val::LI && b.k == Val::LI) {
        if (a.li->size() != b.li->size()) return false;
        for (size_t i = 0; i < a.li->size(); i++) { if (!pyhp_rt_eq((*a.li)[i], (*b.li)[i])) return false; }
        return true;
    }
    if (a.k == Val::DI && b.k == Val::DI) {
        if (a.di->size() != b.di->size()) return false;
        for (const auto& p : *a.di) {
            bool found = false;
            for (const auto& q : *b.di) { if (q.first == p.first) { if (!pyhp_rt_eq(p.second, q.second)) return false; found = true; break; } }
            if (!found) return false;
        }
        return true;
    }
    if (a.k == Val::ER || b.k == Val::ER || a.k == Val::FN || b.k == Val::FN) return &a == &b;
    if (a.k == Val::BO || b.k == Val::BO) {
        if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
            double x = a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a);
            double y = b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b);
            return x == y;
        }
        return false;
    }
    if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
        if (a.k == Val::IN && b.k == Val::IN) return a.i == b.i;
        double x = a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a);
        double y = b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b);
        return x == y;
    }
    if (a.k == Val::ST && b.k == Val::ST) return *a.s == *b.s;
    if (a.k == Val::NUL && b.k == Val::NUL) return true;
    return false;
}

static int pyhp_rt_cmp(const Val& a, const Val& b, const char* op);
static int pyhp_rt_cmp(const Val& a, const Val& b, const char* op) {
    if (a.k == Val::BO && b.k == Val::BO) {
        int x = a.b ? 1 : 0, y = b.b ? 1 : 0;
        return x < y ? -1 : x > y ? 1 : 0;
    }
    if (a.k == Val::BO) { return pyhp_rt_cmp(Val::mk((int64_t)(a.b ? 1 : 0)), b, op); }
    if (b.k == Val::BO) { return pyhp_rt_cmp(a, Val::mk((int64_t)(b.b ? 1 : 0)), op); }
    if (pyhp_rt_is_num(a) && pyhp_rt_is_num(b)) {
        if (a.k == Val::IN && b.k == Val::IN) return a.i < b.i ? -1 : a.i > b.i ? 1 : 0;
        double x = a.k == Val::FL ? a.f : (double)pyhp_rt_as_int(a);
        double y = b.k == Val::FL ? b.f : (double)pyhp_rt_as_int(b);
        return x < y ? -1 : x > y ? 1 : 0;
    }
    if (a.k == Val::ST && b.k == Val::ST) return a.s->compare(*b.s) < 0 ? -1 : a.s->compare(*b.s) > 0 ? 1 : 0;
    if (a.k == Val::LI && b.k == Val::LI) {
        size_t n = std::min(a.li->size(), b.li->size());
        for (size_t i = 0; i < n; i++) {
            int c = pyhp_rt_cmp((*a.li)[i], (*b.li)[i], op);
            if (c != 0) return c;
        }
        return a.li->size() < b.li->size() ? -1 : a.li->size() > b.li->size() ? 1 : 0;
    }
    pyhp_rt_throw("TypeError", std::string("'") + op + "' not supported between instances of '" + pyhp_rt_type_name(a) + "' and '" + pyhp_rt_type_name(b) + "'");
    return 0;
}

static bool pyhp_rt_in(const Val& needle, const Val& hay) {
    if (hay.k == Val::LI) {
        for (const Val& x : *hay.li) { if (pyhp_rt_eq(x, needle)) return true; }
        return false;
    }
    if (hay.k == Val::DI) {
        std::string nk = pyhp_rt_key_encode(needle);
        for (const auto& p : *hay.di) { if (p.first == nk) return true; }
        return false;
    }
    if (hay.k == Val::ST) {
        if (needle.k != Val::ST) pyhp_rt_throw("TypeError", "'in <string>' requires a string needle, got " + pyhp_rt_type_name(needle));
        return needle.s->empty() || hay.s->find(*needle.s) != std::string::npos;
    }
    pyhp_rt_throw("TypeError", "'in' requires a list, dict or string on the right side, got " + pyhp_rt_type_name(hay));
    return false;
}

/* ---------------- indexing, slicing, iteration ---------------- */
static Val pyhp_rt_get(const Val& c, const Val& idx) {
    if (c.k == Val::LI) {
        if (idx.k != Val::IN && idx.k != Val::BO) pyhp_rt_throw("TypeError", "list indices must be int, got " + pyhp_rt_type_name(idx));
        int64_t j = pyhp_rt_as_int(idx);
        if (j < 0) j += (int64_t)c.li->size();
        if (j < 0 || j >= (int64_t)c.li->size())
            pyhp_rt_throw("IndexError", "list index " + std::to_string(pyhp_rt_as_int(idx)) + " out of range (length " + std::to_string(c.li->size()) + ")");
        return (*c.li)[(size_t)j];
    }
    if (c.k == Val::DI) {
        std::string k = pyhp_rt_key_encode(idx);
        for (const auto& p : *c.di) { if (p.first == k) return p.second; }
        pyhp_rt_throw("KeyError", "key not found: " + pyhp_rt_repr(idx));
    }
    if (c.k == Val::ST) {
        if (idx.k != Val::IN && idx.k != Val::BO) pyhp_rt_throw("TypeError", "string indices must be int, got " + pyhp_rt_type_name(idx));
        int64_t j = pyhp_rt_as_int(idx);
        if (j < 0) j += (int64_t)c.s->size();
        if (j < 0 || j >= (int64_t)c.s->size())
            pyhp_rt_throw("IndexError", "string index " + std::to_string(pyhp_rt_as_int(idx)) + " out of range (length " + std::to_string(c.s->size()) + ")");
        return Val::mk(std::string(1, (*c.s)[(size_t)j]));
    }
    pyhp_rt_throw("TypeError", "'" + pyhp_rt_type_name(c) + "' object is not subscriptable");
    return Val::nul();
}
static void pyhp_rt_set(const Val& c, const Val& idx, const Val& v) {
    if (c.k == Val::LI) {
        if (idx.k != Val::IN && idx.k != Val::BO) pyhp_rt_throw("TypeError", "list indices must be int, got " + pyhp_rt_type_name(idx));
        int64_t j = pyhp_rt_as_int(idx);
        if (j < 0) j += (int64_t)c.li->size();
        if (j < 0 || j >= (int64_t)c.li->size())
            pyhp_rt_throw("IndexError", "list assignment index " + std::to_string(pyhp_rt_as_int(idx)) + " out of range (length " + std::to_string(c.li->size()) + ")");
        (*c.li)[(size_t)j] = v;
        return;
    }
    if (c.k == Val::DI) {
        std::string k = pyhp_rt_key_encode(idx);
        for (auto& p : *c.di) { if (p.first == k) { p.second = v; return; } }
        c.di->push_back({k, v});
        return;
    }
    if (c.k == Val::ST) pyhp_rt_throw("TypeError", "strings are immutable; build a new string instead");
    pyhp_rt_throw("TypeError", "'" + pyhp_rt_type_name(c) + "' object does not support item assignment");
}
static std::vector<Val> pyhp_rt_slice_arr(const std::vector<Val>& a, const Val& start, const Val& stop, const Val& step) {
    int64_t n = (int64_t)a.size();
    int64_t st = step.k == Val::NUL ? 1 : pyhp_rt_as_int(step);
    if (st == 0) pyhp_rt_throw("ValueError", "slice step cannot be zero");
    std::vector<Val> out;
    if (st > 0) {
        int64_t s = start.k == Val::NUL ? 0 : (pyhp_rt_as_int(start) < 0 ? std::max((int64_t)0, n + pyhp_rt_as_int(start)) : std::min(pyhp_rt_as_int(start), n));
        int64_t e = stop.k == Val::NUL ? n : (pyhp_rt_as_int(stop) < 0 ? std::max((int64_t)0, n + pyhp_rt_as_int(stop)) : std::min(pyhp_rt_as_int(stop), n));
        for (int64_t i = s; i < e; i += st) out.push_back(a[(size_t)i]);
        return out;
    }
    int64_t s = start.k == Val::NUL ? n - 1 : (pyhp_rt_as_int(start) < 0 ? n + pyhp_rt_as_int(start) : std::min(pyhp_rt_as_int(start), n - 1));
    int64_t e = stop.k == Val::NUL ? -1 : (pyhp_rt_as_int(stop) < 0 ? n + pyhp_rt_as_int(stop) : pyhp_rt_as_int(stop));
    for (int64_t i = s; i > e; i += st) { if (i >= 0 && i < n) out.push_back(a[(size_t)i]); }
    return out;
}
static Val pyhp_rt_slice(const Val& c, const Val& start, const Val& stop, const Val& step) {
    if (c.k == Val::LI) return pyhp_rt_list(pyhp_rt_slice_arr(*c.li, start, stop, step));
    if (c.k == Val::ST) {
        std::vector<Val> chars;
        for (char ch : *c.s) chars.push_back(Val::mk(std::string(1, ch)));
        std::vector<Val> sliced = pyhp_rt_slice_arr(chars, start, stop, step);
        std::string out;
        for (const Val& x : sliced) out += *x.s;
        return Val::mk(out);
    }
    pyhp_rt_throw("TypeError", "'" + pyhp_rt_type_name(c) + "' object is not sliceable");
    return Val::nul();
}
static std::vector<std::pair<Val, Val>> pyhp_rt_pairs(const Val& v) {
    std::vector<std::pair<Val, Val>> out;
    if (v.k == Val::LI) {
        int64_t i = 0;
        for (const Val& x : *v.li) { out.push_back({Val::mk(i++), x}); }
        return out;
    }
    if (v.k == Val::DI) {
        for (const auto& p : *v.di) { out.push_back({pyhp_rt_key_decode(p.first), p.second}); }
        return out;
    }
    if (v.k == Val::ST) {
        int64_t i = 0;
        for (char ch : *v.s) { out.push_back({Val::mk(i++), Val::mk(std::string(1, ch))}); }
        return out;
    }
    pyhp_rt_throw("TypeError", "'" + pyhp_rt_type_name(v) + "' object is not iterable");
    return out;
}
static std::vector<Val> pyhp_rt_itervals(const Val& v) {
    std::vector<Val> out;
    if (v.k == Val::LI) { for (const Val& x : *v.li) out.push_back(x); return out; }
    if (v.k == Val::DI) { for (const auto& p : *v.di) out.push_back(pyhp_rt_key_decode(p.first)); return out; }
    if (v.k == Val::ST) { for (char ch : *v.s) out.push_back(Val::mk(std::string(1, ch))); return out; }
    pyhp_rt_throw("TypeError", "'" + pyhp_rt_type_name(v) + "' object is not iterable");
    return out;
}
static Val pyhp_rt_rest(std::vector<Val>& args, size_t from) {
    Val v = Val::mklist();
    for (size_t i = from; i < args.size(); i++) v.li->push_back(args[i]);
    return v;
}
static Val pyhp_rt_wrapfn(const std::string& name, PyFn f) {
    Val v;
    v.k = Val::FN;
    v.fn = std::make_shared<PyFn>(std::move(f));
    v.et = name;
    return v;
}
static Val pyhp_rt_callfn(const Val& f, std::vector<Val> args);
static Val pyhp_rt_call_kw(const std::string& name, std::vector<Val> A,
                           const std::vector<std::string>& KN, const std::vector<Val>& KV) {
    if (name == "sorted") {
        if (A.size() != 1) pyhp_rt_throw("TypeError", "sorted() takes exactly 1 positional argument (" + std::to_string(A.size()) + " given)");
        bool rev = false; bool hasKey = false; Val key;
        for (size_t i = 0; i < KN.size(); i++) {
            if (KN[i] == "reverse") rev = pyhp_rt_truthy(KV[i]);
            else if (KN[i] == "key") { hasKey = true; key = KV[i]; }
            else pyhp_rt_throw("TypeError", "sorted() got an unexpected keyword argument '" + KN[i] + "'");
        }
        std::vector<Val> out = pyhp_rt_itervals(A[0]);
        if (hasKey) {
            std::vector<std::pair<Val, Val>> dec;
            dec.reserve(out.size());
            for (auto& v : out) dec.push_back({pyhp_rt_callfn(key, {v}), v});
            std::stable_sort(dec.begin(), dec.end(), [](const std::pair<Val, Val>& x, const std::pair<Val, Val>& y) {
                return pyhp_rt_cmp(x.first, y.first, "<") < 0;
            });
            out.clear();
            for (auto& p : dec) out.push_back(p.second);
        } else {
            std::stable_sort(out.begin(), out.end(), [](const Val& x, const Val& y) { return pyhp_rt_cmp(x, y, "<") < 0; });
        }
        if (rev) std::reverse(out.begin(), out.end());
        return pyhp_rt_list(std::move(out));
    }
    pyhp_rt_throw("TypeError", name + "() accepts positional arguments only");
    return Val::nul();
}
static Val pyhp_rt_callfn(const Val& f, std::vector<Val> args) {
    if (f.k == Val::FN) return (*f.fn)(args);
    pyhp_rt_throw("TypeError", "value is not callable (" + pyhp_rt_type_name(f) + ")");
    return Val::nul();
}
static Val pyhp_rt_errval(const PyError& e) {
    Val v;
    v.k = Val::ER;
    v.et = e.type;
    v.s = std::make_shared<std::string>(e.what());
    return v;
}
static bool pyhp_rt_catch_match(const PyError& e, const std::string& t) {
    return t == "Exception" || e.type == t;
}
static Val pyhp_rt_checktype(Val v, const std::string& t, const std::string& name) {
    auto bad = [&]() {
        pyhp_rt_throw("TypeError", "type mismatch: cannot assign " + pyhp_rt_type_name(v) + " to " + t + " variable '" + name + "'");
    };
    if (t == "int") { if (v.k != Val::IN) bad(); return v; }
    if (t == "float") {
        if (v.k == Val::IN) return Val::mk((double)v.i);
        if (v.k != Val::FL) bad();
        return v;
    }
    if (t == "string") { if (v.k != Val::ST) bad(); return v; }
    if (t == "bool") { if (v.k != Val::BO) bad(); return v; }
    if (t == "list") { if (v.k != Val::LI) bad(); return v; }
    if (t == "dict") { if (v.k != Val::DI) bad(); return v; }
    return v;
}

/* ---------------- members & methods ---------------- */
static Val pyhp_rt_member(const Val& obj, const std::string& name) {
    if (obj.k == Val::ER && name == "message") return Val::mk(*obj.s);
    if (obj.k == Val::DI) {
        for (const auto& p : *obj.di) { if (p.first == name) return p.second; }
    }
    pyhp_rt_throw("TypeError", "'" + pyhp_rt_type_name(obj) + "' object has no property '" + name + "'");
    return Val::nul();
}
static void pyhp_rt_member_set(const Val& obj, const std::string& name, const Val& v) {
    if (obj.k == Val::DI) {
        for (auto& p : *obj.di) { if (p.first == name) { p.second = v; return; } }
        obj.di->push_back({name, v});
        return;
    }
    pyhp_rt_throw("TypeError", "cannot set property '" + name + "' on " + pyhp_rt_type_name(obj));
}

static std::vector<std::string> pyhp_rt_split_ws(const std::string& s) {
    std::vector<std::string> out;
    size_t i = 0;
    while (i < s.size()) {
        while (i < s.size() && std::isspace((unsigned char)s[i])) i++;
        size_t j = i;
        while (j < s.size() && !std::isspace((unsigned char)s[j])) j++;
        if (j > i) out.push_back(s.substr(i, j - i));
        i = j;
    }
    return out;
}
static std::string pyhp_rt_trim(const std::string& s) {
    size_t a = s.find_first_not_of(" \t\n\r\x0B\f");
    if (a == std::string::npos) return "";
    size_t b = s.find_last_not_of(" \t\n\r\x0B\f");
    return s.substr(a, b - a + 1);
}
static Val pyhp_rt_method(const Val& obj, const std::string& name, std::vector<Val> args) {
    auto need = [&](int lo, int hi) {
        int n = (int)args.size();
        if (n < lo || (hi != -1 && n > hi))
            pyhp_rt_throw("TypeError", name + "() expects " + std::to_string(lo) + (hi == -1 ? "+" : ".." + std::to_string(hi)) + " argument(s), got " + std::to_string(n));
    };
    auto strarg = [&](size_t i) -> const std::string& {
        if (args[i].k != Val::ST) pyhp_rt_throw("TypeError", name + "() argument must be a string, got " + pyhp_rt_type_name(args[i]));
        return *args[i].s;
    };
    if (obj.k == Val::ST) {
        const std::string& s = *obj.s;
        if (name == "upper")    { need(0, 0); std::string o = s; for (auto& c : o) c = (char)std::toupper((unsigned char)c); return Val::mk(o); }
        if (name == "lower")    { need(0, 0); std::string o = s; for (auto& c : o) c = (char)std::tolower((unsigned char)c); return Val::mk(o); }
        if (name == "capitalize") {
            need(0, 0);
            std::string o = s;
            if (!o.empty()) {
                o[0] = (char)std::toupper((unsigned char)o[0]);
                for (size_t i = 1; i < o.size(); i++) o[i] = (char)std::tolower((unsigned char)o[i]);
            }
            return Val::mk(o);
        }
        if (name == "strip")    { need(0, 0); return Val::mk(pyhp_rt_trim(s)); }
        if (name == "lstrip")   { need(0, 0); size_t a = s.find_first_not_of(" \t\n\r\x0B\f"); return Val::mk(a == std::string::npos ? "" : s.substr(a)); }
        if (name == "rstrip")   { need(0, 0); size_t b = s.find_last_not_of(" \t\n\r\x0B\f"); return Val::mk(b == std::string::npos ? "" : s.substr(0, b + 1)); }
        if (name == "split") {
            need(0, 1);
            if (args.empty()) {
                std::vector<Val> parts;
                for (auto& p : pyhp_rt_split_ws(pyhp_rt_trim(s))) parts.push_back(Val::mk(p));
                return pyhp_rt_list(std::move(parts));
            }
            const std::string& sep = strarg(0);
            if (sep.empty()) pyhp_rt_throw("ValueError", "empty separator");
            std::vector<Val> parts;
            size_t pos = 0;
            while (true) {
                size_t hit = s.find(sep, pos);
                if (hit == std::string::npos) { parts.push_back(Val::mk(s.substr(pos))); break; }
                parts.push_back(Val::mk(s.substr(pos, hit - pos)));
                pos = hit + sep.size();
            }
            return pyhp_rt_list(std::move(parts));
        }
        if (name == "replace") {
            need(2, 2);
            const std::string& from = strarg(0);
            const std::string& to = strarg(1);
            std::string out;
            size_t pos = 0;
            if (!from.empty()) {
                while (true) {
                    size_t hit = s.find(from, pos);
                    if (hit == std::string::npos) { out += s.substr(pos); break; }
                    out += s.substr(pos, hit - pos) + to;
                    pos = hit + from.size();
                }
                return Val::mk(out);
            }
            return Val::mk(s);
        }
        if (name == "startswith") { need(1, 1); return Val::mk(s.rfind(strarg(0), 0) == 0); }
        if (name == "endswith")   { need(1, 1); const std::string& suf = strarg(0); return Val::mk(s.size() >= suf.size() && s.compare(s.size() - suf.size(), suf.size(), suf) == 0); }
        if (name == "contains")   { need(1, 1); return Val::mk(s.find(strarg(0)) != std::string::npos); }
        if (name == "find")       { need(1, 1); size_t p = s.find(strarg(0)); return Val::mk(p == std::string::npos ? (int64_t)-1 : (int64_t)p); }
        if (name == "count") {
            need(1, 1);
            const std::string& sub = strarg(0);
            int64_t c = 0;
            if (!sub.empty()) {
                for (size_t pos = s.find(sub); pos != std::string::npos; pos = s.find(sub, pos + sub.size())) c++;
            }
            return Val::mk(c);
        }
        if (name == "join") {
            need(1, 1);
            std::string out;
            bool first = true;
            for (const Val& x : pyhp_rt_itervals(args[0])) {
                if (!first) out += s;
                first = false;
                out += pyhp_rt_tostr(x);
            }
            return Val::mk(out);
        }
        if (name == "chars") {
            need(0, 0);
            std::vector<Val> parts;
            for (char c : s) parts.push_back(Val::mk(std::string(1, c)));
            return pyhp_rt_list(std::move(parts));
        }
        pyhp_rt_throw("TypeError", "str object has no method '" + name + "'");
    }
    if (obj.k == Val::LI) {
        auto& a = *obj.li;
        if (name == "append")  { need(1, 1); a.push_back(args[0]); return Val::nul(); }
        if (name == "pop") {
            need(0, 1);
            int64_t n = (int64_t)a.size();
            if (n == 0) pyhp_rt_throw("IndexError", "pop from empty list");
            int64_t i = args.empty() ? -1 : pyhp_rt_as_int(args[0]);
            if (i < 0) i += n;
            if (i < 0 || i >= n) pyhp_rt_throw("IndexError", "pop index out of range");
            Val v = a[(size_t)i];
            a.erase(a.begin() + i);
            return v;
        }
        if (name == "extend") {
            need(1, 1);
            for (const Val& x : pyhp_rt_itervals(args[0])) a.push_back(x);
            return Val::nul();
        }
        if (name == "insert") {
            need(2, 2);
            int64_t n = (int64_t)a.size();
            int64_t i = pyhp_rt_as_int(args[0]);
            if (i < 0) i = std::max((int64_t)0, n + i);
            if (i > n) i = n;
            a.insert(a.begin() + i, args[1]);
            return Val::nul();
        }
        if (name == "remove") {
            need(1, 1);
            for (size_t i = 0; i < a.size(); i++) {
                if (pyhp_rt_eq(a[i], args[0])) { a.erase(a.begin() + i); return Val::nul(); }
            }
            pyhp_rt_throw("ValueError", "list.remove(x): x not in list");
        }
        if (name == "index") {
            need(1, 1);
            for (size_t i = 0; i < a.size(); i++) { if (pyhp_rt_eq(a[i], args[0])) return Val::mk((int64_t)i); }
            pyhp_rt_throw("ValueError", "value not in list");
        }
        if (name == "count") {
            need(1, 1);
            int64_t c = 0;
            for (const Val& x : a) { if (pyhp_rt_eq(x, args[0])) c++; }
            return Val::mk(c);
        }
        if (name == "sort")    { need(0, 0); std::stable_sort(a.begin(), a.end(), [](const Val& x, const Val& y) { return pyhp_rt_cmp(x, y, "<") < 0; }); return Val::nul(); }
        if (name == "reverse") { need(0, 0); std::reverse(a.begin(), a.end()); return Val::nul(); }
        if (name == "clear")   { need(0, 0); a.clear(); return Val::nul(); }
        if (name == "copy")    { need(0, 0); return pyhp_rt_list(a); }
        pyhp_rt_throw("TypeError", "list object has no method '" + name + "'");
    }
    if (obj.k == Val::DI) {
        auto& d = *obj.di;
        auto findKey = [&](const std::string& k) -> Val* {
            for (auto& p : d) { if (p.first == k) return &p.second; }
            return nullptr;
        };
        if (name == "keys")   { need(0, 0); std::vector<Val> ks; for (auto& p : d) ks.push_back(pyhp_rt_key_decode(p.first)); return pyhp_rt_list(std::move(ks)); }
        if (name == "values") { need(0, 0); std::vector<Val> vs; for (auto& p : d) vs.push_back(p.second); return pyhp_rt_list(std::move(vs)); }
        if (name == "items")  {
            need(0, 0);
            std::vector<Val> its;
            for (auto& p : d) { Val pair = Val::mklist(); pair.li->push_back(pyhp_rt_key_decode(p.first)); pair.li->push_back(p.second); its.push_back(pair); }
            return pyhp_rt_list(std::move(its));
        }
        if (name == "get") {
            need(1, 2);
            std::string k = pyhp_rt_key_encode(args[0]);
            Val* v = findKey(k);
            if (v) return *v;
            return args.size() > 1 ? args[1] : Val::nul();
        }
        if (name == "has") {
            need(1, 1);
            return Val::mk(findKey(pyhp_rt_key_encode(args[0])) != nullptr);
        }
        if (name == "remove") {
            need(1, 1);
            std::string k = pyhp_rt_key_encode(args[0]);
            for (size_t i = 0; i < d.size(); i++) {
                if (d[i].first == k) {
                    Val v = d[i].second;
                    d.erase(d.begin() + i);
                    return v;
                }
            }
            pyhp_rt_throw("KeyError", "key not found: " + pyhp_rt_repr(args[0]));
        }
        if (name == "clear") { need(0, 0); d.clear(); return Val::nul(); }
        if (name == "copy")  { need(0, 0); Val c = Val::mkdict(); *c.di = d; return c; }
        if (name == "merge") {
            need(1, 1);
            if (args[0].k != Val::DI) pyhp_rt_throw("TypeError", "dict.merge() expects a dict, got " + pyhp_rt_type_name(args[0]));
            for (auto& p : *args[0].di) {
                bool replaced = false;
                for (auto& q : d) { if (q.first == p.first) { q.second = p.second; replaced = true; break; } }
                if (!replaced) d.push_back(p);
            }
            return Val::nul();
        }
        // dot-call on dict-stored callables (module tables etc.)
        std::string k = pyhp_rt_key_encode(Val::mk(name));
        for (auto& p : d) {
            if (p.first == k && p.second.k == Val::FN) return pyhp_rt_callfn(p.second, args);
        }
        pyhp_rt_throw("TypeError", "dict object has no method '" + name + "'");
    }
    pyhp_rt_throw("TypeError", "'" + pyhp_rt_type_name(obj) + "' object has no method '" + name + "'");
    return Val::nul();
}

/* ---------------- SHA-256 (FIPS 180-4) ---------------- */
struct PySHA256 {
    unsigned int h[8];
    unsigned long long len;
    unsigned char buf[64];
    size_t bufLen;
    PySHA256() : len(0), bufLen(0) {
        static const unsigned int init[8] = {
            0x6a09e667u, 0xbb67ae85u, 0x3c6ef372u, 0xa54ff53au,
            0x510e527fu, 0x9b05688cu, 0x1f83d9abu, 0x5be0cd19u };
        for (int i = 0; i < 8; i++) h[i] = init[i];
    }
};
static unsigned int pyhp_rt_rotr(unsigned int x, int n) { return (x >> n) | (x << (32 - n)); }
static void pyhp_rt_sha_block(PySHA256& c, const unsigned char* p) {
    static const unsigned int K[64] = {
        0x428a2f98u,0x71374491u,0xb5c0fbcfu,0xe9b5dba5u,0x3956c25bu,0x59f111f1u,0x923f82a4u,0xab1c5ed5u,
        0xd807aa98u,0x12835b01u,0x243185beu,0x550c7dc3u,0x72be5d74u,0x80deb1feu,0x9bdc06a7u,0xc19bf174u,
        0xe49b69c1u,0xefbe4786u,0x0fc19dc6u,0x240ca1ccu,0x2de92c6fu,0x4a7484aau,0x5cb0a9dcu,0x76f988dau,
        0x983e5152u,0xa831c66du,0xb00327c8u,0xbf597fc7u,0xc6e00bf3u,0xd5a79147u,0x06ca6351u,0x14292967u,
        0x27b70a85u,0x2e1b2138u,0x4d2c6dfcu,0x53380d13u,0x650a7354u,0x766a0abbu,0x81c2c92eu,0x92722c85u,
        0xa2bfe8a1u,0xa81a664bu,0xc24b8b70u,0xc76c51a3u,0xd192e819u,0xd6990624u,0xf40e3585u,0x106aa070u,
        0x19a4c116u,0x1e376c08u,0x2748774cu,0x34b0bcb5u,0x391c0cb3u,0x4ed8aa4au,0x5b9cca4fu,0x682e6ff3u,
        0x748f82eeu,0x78a5636fu,0x84c87814u,0x8cc70208u,0x90befffau,0xa4506cebu,0xbef9a3f7u,0xc67178f2u };
    unsigned int w[64];
    for (int i = 0; i < 16; i++) {
        w[i] = ((unsigned int)p[i * 4] << 24) | ((unsigned int)p[i * 4 + 1] << 16)
             | ((unsigned int)p[i * 4 + 2] << 8) | (unsigned int)p[i * 4 + 3];
    }
    for (int i = 16; i < 64; i++) {
        unsigned int s0 = pyhp_rt_rotr(w[i - 15], 7) ^ pyhp_rt_rotr(w[i - 15], 18) ^ (w[i - 15] >> 3);
        unsigned int s1 = pyhp_rt_rotr(w[i - 2], 17) ^ pyhp_rt_rotr(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    unsigned int a = c.h[0], b = c.h[1], cc = c.h[2], d = c.h[3];
    unsigned int e = c.h[4], f = c.h[5], g = c.h[6], hh = c.h[7];
    for (int i = 0; i < 64; i++) {
        unsigned int S1 = pyhp_rt_rotr(e, 6) ^ pyhp_rt_rotr(e, 11) ^ pyhp_rt_rotr(e, 25);
        unsigned int ch = (e & f) ^ ((~e) & g);
        unsigned int t1 = hh + S1 + ch + K[i] + w[i];
        unsigned int S0 = pyhp_rt_rotr(a, 2) ^ pyhp_rt_rotr(a, 13) ^ pyhp_rt_rotr(a, 22);
        unsigned int maj = (a & b) ^ (a & cc) ^ (b & cc);
        unsigned int t2 = S0 + maj;
        hh = g; g = f; f = e; e = d + t1;
        d = cc; cc = b; b = a; a = t1 + t2;
    }
    c.h[0] += a; c.h[1] += b; c.h[2] += cc; c.h[3] += d;
    c.h[4] += e; c.h[5] += f; c.h[6] += g; c.h[7] += hh;
}
static std::string pyhp_rt_sha256(const std::string& msg) {
    PySHA256 c;
    const unsigned char* m = (const unsigned char*)msg.data();
    size_t n = msg.size();
    size_t done = 0;
    while (n - done >= 64) { pyhp_rt_sha_block(c, m + done); done += 64; }
    unsigned char tail[128];
    size_t rem = n - done;
    for (size_t i = 0; i < rem; i++) tail[i] = m[done + i];
    tail[rem] = 0x80;
    size_t total = (rem + 1 <= 56) ? 64 : 128;
    for (size_t i = rem + 1; i < total; i++) tail[i] = 0;
    unsigned long long bits = (unsigned long long)n * 8;
    for (int i = 0; i < 8; i++) tail[total - 1 - i] = (unsigned char)((bits >> (8 * i)) & 0xFF);
    pyhp_rt_sha_block(c, tail);
    if (total == 128) pyhp_rt_sha_block(c, tail + 64);
    char out[65];
    for (int i = 0; i < 8; i++) std::snprintf(out + i * 8, 9, "%08x", c.h[i]);
    return std::string(out, 64);
}

/* ---------------- builtins ---------------- */
static double pyhp_rt_num1(const Val& v, const char* who) {
    if (v.k == Val::IN) return (double)v.i;
    if (v.k == Val::FL) return v.f;
    if (v.k == Val::BO) return v.b ? 1.0 : 0.0;
    pyhp_rt_throw("TypeError", std::string(who) + "() requires a number, got " + pyhp_rt_type_name(v));
    return 0;
}
static int64_t pyhp_rt_int1(const Val& v, const char* who) {
    if (v.k == Val::IN) return v.i;
    if (v.k == Val::BO) return v.b ? 1 : 0;
    if (v.k == Val::FL) {
        if (std::floor(v.f) != v.f) pyhp_rt_throw("TypeError", std::string(who) + "() expects an int, got float");
        return (int64_t)v.f;
    }
    pyhp_rt_throw("TypeError", std::string(who) + "() expects an int, got " + pyhp_rt_type_name(v));
    return 0;
}
static const std::string& pyhp_rt_str1(const Val& v, const char* who) {
    if (v.k != Val::ST) pyhp_rt_throw("TypeError", std::string(who) + "() argument must be a string, got " + pyhp_rt_type_name(v));
    return *v.s;
}
static int64_t pyhp_rt_int_conv(const Val& v) {
    if (v.k == Val::BO) return v.b ? 1 : 0;
    if (v.k == Val::IN) return v.i;
    if (v.k == Val::FL) return (int64_t)v.f;
    if (v.k == Val::ST) {
        const std::string t = pyhp_rt_trim(*v.s);
        char* end = nullptr;
        long long r = std::strtoll(t.c_str(), &end, 10);
        if (end && *end == '\0' && !t.empty()) return (int64_t)r;
        pyhp_rt_throw("ValueError", "invalid literal for int(): '" + *v.s + "'");
    }
    pyhp_rt_throw("TypeError", "int() expects a number or string, got " + pyhp_rt_type_name(v));
    return 0;
}
static double pyhp_rt_float_conv(const Val& v) {
    if (v.k == Val::BO) return v.b ? 1.0 : 0.0;
    if (v.k == Val::IN) return (double)v.i;
    if (v.k == Val::FL) return v.f;
    if (v.k == Val::ST) {
        const std::string t = pyhp_rt_trim(*v.s);
        char* end = nullptr;
        double r = std::strtod(t.c_str(), &end);
        if (end && *end == '\0' && !t.empty()) return r;
        pyhp_rt_throw("ValueError", "invalid literal for float(): '" + *v.s + "'");
    }
    pyhp_rt_throw("TypeError", "float() expects a number or string, got " + pyhp_rt_type_name(v));
    return 0;
}

/* base64 (RFC 4648, strict) */
static const char* pyhp_rt_b64t = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
static std::string pyhp_rt_b64e(const std::string& in) {
    std::string out;
    int val = 0, valb = -6;
    for (unsigned char c : in) {
        val = ((val << 8) & 0xFFFFFF) + c;
        valb += 8;
        while (valb >= 0) { out.push_back(pyhp_rt_b64t[(val >> valb) & 0x3F]); valb -= 6; }
    }
    if (valb > -6) out.push_back(pyhp_rt_b64t[((val << 8) >> (valb + 8)) & 0x3F]);
    while (out.size() % 4) out.push_back('=');
    return out;
}
static std::string pyhp_rt_b64d(const std::string& in) {
    std::vector<int> T(256, -1);
    for (int i = 0; i < 64; i++) T[(unsigned char)pyhp_rt_b64t[i]] = i;
    std::string out;
    int val = 0, valb = -8;
    for (unsigned char c : in) {
        if (c == '=') break;
        if (T[c] == -1) pyhp_rt_throw("ValueError", "base64d(): invalid base64 input");
        val = ((val << 6) & 0xFFFFFF) + T[c];
        valb += 6;
        if (valb >= 0) { out.push_back(char((val >> valb) & 0xFF)); valb -= 8; }
    }
    return out;
}
static std::string pyhp_rt_urlenc(const std::string& s) {
    static const char* hex = "0123456789ABCDEF";
    std::string out;
    for (unsigned char c : s) {
        if (std::isalnum(c) || c == '-' || c == '_' || c == '.' || c == '~') out.push_back((char)c);
        else { out.push_back('%'); out.push_back(hex[c >> 4]); out.push_back(hex[c & 15]); }
    }
    return out;
}
static int pyhp_rt_hexv(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}
static std::string pyhp_rt_urldec(const std::string& s) {
    std::string out;
    for (size_t i = 0; i < s.size(); i++) {
        if (s[i] == '%' && i + 2 < s.size() && pyhp_rt_hexv(s[i + 1]) >= 0 && pyhp_rt_hexv(s[i + 2]) >= 0) {
            out.push_back((char)(pyhp_rt_hexv(s[i + 1]) * 16 + pyhp_rt_hexv(s[i + 2])));
            i += 2;
        } else out.push_back(s[i]);
    }
    return out;
}

/* minimal JSON support */
static void pyhp_rt_json_ws(const char*& p) { while (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r') p++; }
static Val pyhp_rt_json_parse(const char*& p);
static Val pyhp_rt_json_parse(const char*& p) {
    pyhp_rt_json_ws(p);
    if (*p == '{') {
        p++;
        Val d = Val::mkdict();
        pyhp_rt_json_ws(p);
        if (*p == '}') { p++; return d; }
        while (true) {
            pyhp_rt_json_ws(p);
            if (*p != '"') pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — expected string key");
            std::string key;
            p++;
            while (*p && *p != '"') {
                if (*p == '\\' && p[1]) {
                    p++;
                    switch (*p) {
                        case 'n': key.push_back('\n'); break;
                        case 't': key.push_back('\t'); break;
                        case 'r': key.push_back('\r'); break;
                        case 'b': key.push_back('\b'); break;
                        case 'f': key.push_back('\f'); break;
                        case '/': key.push_back('/'); break;
                        case '"': key.push_back('"'); break;
                        case '\\': key.push_back('\\'); break;
                        case 'u': {
                            if (!p[1] || !p[2] || !p[3] || !p[4]) pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — bad \\u escape");
                            std::string hex(p + 1, p + 5);
                            int cp = (int)std::strtol(hex.c_str(), nullptr, 16);
                            // encode as UTF-8 (BMP only; surrogates simplified)
                            if (cp < 0x80) key.push_back((char)cp);
                            else if (cp < 0x800) { key.push_back((char)(0xC0 | (cp >> 6))); key.push_back((char)(0x80 | (cp & 0x3F))); }
                            else { key.push_back((char)(0xE0 | (cp >> 12))); key.push_back((char)(0x80 | ((cp >> 6) & 0x3F))); key.push_back((char)(0x80 | (cp & 0x3F))); }
                            p += 4;
                            break;
                        }
                        default: key.push_back(*p);
                    }
                    p++;
                } else { key.push_back(*p); p++; }
            }
            if (*p != '"') pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — unterminated string");
            p++;
            pyhp_rt_json_ws(p);
            if (*p != ':') pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — expected ':'");
            p++;
            Val v = pyhp_rt_json_parse(p);
            d.di->push_back({key, v});
            pyhp_rt_json_ws(p);
            if (*p == ',') { p++; continue; }
            if (*p == '}') { p++; return d; }
            pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — expected ',' or '}'");
        }
    }
    if (*p == '[') {
        p++;
        Val l = Val::mklist();
        pyhp_rt_json_ws(p);
        if (*p == ']') { p++; return l; }
        while (true) {
            Val v = pyhp_rt_json_parse(p);
            l.li->push_back(v);
            pyhp_rt_json_ws(p);
            if (*p == ',') { p++; continue; }
            if (*p == ']') { p++; return l; }
            pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — expected ',' or ']'");
        }
    }
    if (*p == '"') {
        p++;
        std::string out;
        while (*p && *p != '"') {
            if (*p == '\\' && p[1]) {
                p++;
                switch (*p) {
                    case 'n': out.push_back('\n'); break;
                    case 't': out.push_back('\t'); break;
                    case 'r': out.push_back('\r'); break;
                    case 'b': out.push_back('\b'); break;
                    case 'f': out.push_back('\f'); break;
                    case '/': out.push_back('/'); break;
                    case '"': out.push_back('"'); break;
                    case '\\': out.push_back('\\'); break;
                    case 'u': {
                        if (!p[1] || !p[2] || !p[3] || !p[4]) pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — bad \\u escape");
                        std::string hex(p + 1, p + 5);
                        int cp = (int)std::strtol(hex.c_str(), nullptr, 16);
                        if (cp < 0x80) out.push_back((char)cp);
                        else if (cp < 0x800) { out.push_back((char)(0xC0 | (cp >> 6))); out.push_back((char)(0x80 | (cp & 0x3F))); }
                        else { out.push_back((char)(0xE0 | (cp >> 12))); out.push_back((char)(0x80 | ((cp >> 6) & 0x3F))); out.push_back((char)(0x80 | (cp & 0x3F))); }
                        p += 4;
                        break;
                    }
                    default: out.push_back(*p);
                }
                p++;
            } else { out.push_back(*p); p++; }
        }
        if (*p != '"') pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — unterminated string");
        p++;
        return Val::mk(out);
    }
    if (std::strncmp(p, "true", 4) == 0) { p += 4; return Val::mk(true); }
    if (std::strncmp(p, "false", 5) == 0) { p += 5; return Val::mk(false); }
    if (std::strncmp(p, "null", 4) == 0) { p += 4; return Val::nul(); }
    // number
    const char* q = p;
    if (*q == '-' || *q == '+') q++;
    bool isFloat = false;
    while (*q >= '0' && *q <= '9') q++;
    if (*q == '.') { isFloat = true; q++; while (*q >= '0' && *q <= '9') q++; }
    if (*q == 'e' || *q == 'E') {
        isFloat = true;
        q++;
        if (*q == '-' || *q == '+') q++;
        while (*q >= '0' && *q <= '9') q++;
    }
    if (q == p) pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — unexpected character");
    std::string num(p, q);
    p = q;
    if (isFloat) return Val::mk(std::strtod(num.c_str(), nullptr));
    return Val::mk((int64_t)std::strtoll(num.c_str(), nullptr, 10));
}
static void pyhp_rt_json_write(const Val& v, std::string& out);
static void pyhp_rt_json_write(const Val& v, std::string& out) {
    switch (v.k) {
        case Val::NUL: out += "null"; break;
        case Val::BO: out += v.b ? "true" : "false"; break;
        case Val::IN: out += std::to_string(v.i); break;
        case Val::FL: {
            char buf[64];
            std::snprintf(buf, sizeof(buf), "%.14G", v.f);
            std::string r(buf);
            if (r.find('.') == std::string::npos && r.find_first_of("eE") == std::string::npos) r += ".0";
            out += r;
            break;
        }
        case Val::ST: {
            out += '"';
            for (char c : *v.s) {
                switch (c) {
                    case '"': out += "\\\""; break;
                    case '\\': out += "\\\\"; break;
                    case '\n': out += "\\n"; break;
                    case '\t': out += "\\t"; break;
                    case '\r': out += "\\r"; break;
                    default:
                        if ((unsigned char)c < 32) { char b[8]; std::snprintf(b, sizeof(b), "\\u%04x", c); out += b; }
                        else out += c;
                }
            }
            out += '"';
            break;
        }
        case Val::LI: {
            out += '[';
            bool first = true;
            for (const Val& x : *v.li) { if (!first) out += ','; first = false; pyhp_rt_json_write(x, out); }
            out += ']';
            break;
        }
        case Val::DI: {
            out += '{';
            bool first = true;
            for (const auto& p : *v.di) {
                if (!first) out += ',';
                first = false;
                Val k = pyhp_rt_key_decode(p.first);
                pyhp_rt_json_write(k.k == Val::IN ? Val::mk(std::to_string(k.i)) : k, out);
                out += ':';
                pyhp_rt_json_write(p.second, out);
            }
            out += '}';
            break;
        }
        default: pyhp_rt_throw("ValueError", "json_string(): cannot serialize " + pyhp_rt_type_name(v));
    }
}

static Val pyhp_rt_call(const std::string& name, std::vector<Val> A) {
    auto need = [&](int lo, int hi) {
        int n = (int)A.size();
        if (n < lo || (hi != -1 && n > hi)) {
            std::string sig = std::to_string(lo) + (hi == -1 ? "+" : (hi == lo ? "" : ".." + std::to_string(hi)));
            pyhp_rt_throw("TypeError", name + "() takes " + sig + " argument(s), got " + std::to_string(n));
        }
    };
    if (name == "print" || name == "println") {
        std::string out;
        for (size_t i = 0; i < A.size(); i++) { if (i) out += " "; out += pyhp_rt_tostr(A[i]); }
        out += "\n";
        std::fputs(out.c_str(), stdout);
        return Val::nul();
    }
    if (name == "repr")  { need(1, 1); return Val::mk(pyhp_rt_repr(A[0])); }
    if (name == "len") {
        need(1, 1);
        const Val& v = A[0];
        if (v.k == Val::ST) return Val::mk((int64_t)v.s->size());
        if (v.k == Val::LI) return Val::mk((int64_t)v.li->size());
        if (v.k == Val::DI) return Val::mk((int64_t)v.di->size());
        pyhp_rt_throw("TypeError", "len() of unsupported type '" + pyhp_rt_type_name(v) + "'");
    }
    if (name == "range") {
        need(1, 3);
        int64_t s = 0, e = 0, st = 1;
        if (A.size() == 1) { e = pyhp_rt_int1(A[0], "range"); }
        else if (A.size() == 2) { s = pyhp_rt_int1(A[0], "range"); e = pyhp_rt_int1(A[1], "range"); }
        else { s = pyhp_rt_int1(A[0], "range"); e = pyhp_rt_int1(A[1], "range"); st = pyhp_rt_int1(A[2], "range"); }
        if (st == 0) pyhp_rt_throw("ValueError", "range() step cannot be zero");
        std::vector<Val> out;
        if (st > 0) { for (int64_t i = s; i < e; i += st) out.push_back(Val::mk(i)); }
        else { for (int64_t i = s; i > e; i += st) out.push_back(Val::mk(i)); }
        return pyhp_rt_list(std::move(out));
    }
    if (name == "map") {
        need(2, -1);
        std::vector<std::vector<Val>> cols;
        size_t n = SIZE_MAX;
        for (size_t i = 1; i < A.size(); i++) {
            cols.push_back(pyhp_rt_itervals(A[i]));
            n = std::min(n, cols.back().size());
        }
        std::vector<Val> out;
        for (size_t r = 0; r < n; r++) {
            std::vector<Val> row;
            for (auto& c : cols) row.push_back(c[r]);
            out.push_back(pyhp_rt_callfn(A[0], row));
        }
        return pyhp_rt_list(std::move(out));
    }
    if (name == "filter") {
        need(2, 2);
        std::vector<Val> out;
        for (const Val& v : pyhp_rt_itervals(A[1])) {
            std::vector<Val> row{v};
            if (pyhp_rt_truthy(pyhp_rt_callfn(A[0], row))) out.push_back(v);
        }
        return pyhp_rt_list(std::move(out));
    }
    if (name == "zip") {
        need(1, -1);
        std::vector<std::vector<Val>> cols;
        size_t n = SIZE_MAX;
        for (const Val& a : A) { cols.push_back(pyhp_rt_itervals(a)); n = std::min(n, cols.back().size()); }
        std::vector<Val> out;
        for (size_t r = 0; r < n; r++) {
            Val row = Val::mklist();
            for (auto& c : cols) row.li->push_back(c[r]);
            out.push_back(row);
        }
        return pyhp_rt_list(std::move(out));
    }
    if (name == "enumerate") {
        need(1, 2);
        int64_t start = A.size() > 1 ? pyhp_rt_int1(A[1], "enumerate") : 0;
        std::vector<Val> out;
        for (const Val& v : pyhp_rt_itervals(A[0])) {
            Val pair = Val::mklist();
            pair.li->push_back(Val::mk(start++));
            pair.li->push_back(v);
            out.push_back(pair);
        }
        return pyhp_rt_list(std::move(out));
    }
    if (name == "sorted") {
        need(1, 1);
        std::vector<Val> out = pyhp_rt_itervals(A[0]);
        std::stable_sort(out.begin(), out.end(), [](const Val& x, const Val& y) { return pyhp_rt_cmp(x, y, "<") < 0; });
        return pyhp_rt_list(std::move(out));
    }
    if (name == "reversed") {
        need(1, 1);
        std::vector<Val> out = pyhp_rt_itervals(A[0]);
        std::reverse(out.begin(), out.end());
        return pyhp_rt_list(std::move(out));
    }
    if (name == "sum") {
        need(1, 2);
        Val acc = A.size() > 1 ? A[1] : Val::mk((int64_t)0);
        if (!pyhp_rt_is_num(acc)) pyhp_rt_throw("TypeError", "sum() start must be a number");
        for (const Val& v : pyhp_rt_itervals(A[0])) {
            if (!pyhp_rt_is_num(v)) pyhp_rt_throw("TypeError", "sum() requires numbers, got " + pyhp_rt_type_name(v));
            acc = pyhp_rt_add(acc, v);
        }
        return acc;
    }
    if (name == "any") { need(1, 1); for (const Val& v : pyhp_rt_itervals(A[0])) { if (pyhp_rt_truthy(v)) return Val::mk(true); } return Val::mk(false); }
    if (name == "all") { need(1, 1); for (const Val& v : pyhp_rt_itervals(A[0])) { if (!pyhp_rt_truthy(v)) return Val::mk(false); } return Val::mk(true); }
    if (name == "keys")   { need(1, 1); if (A[0].k != Val::DI) pyhp_rt_throw("TypeError", "keys() expects a dict, got " + pyhp_rt_type_name(A[0])); std::vector<Val> noargs; return pyhp_rt_method(A[0], "keys", noargs); }
    if (name == "values") { need(1, 1); if (A[0].k != Val::DI) pyhp_rt_throw("TypeError", "values() expects a dict, got " + pyhp_rt_type_name(A[0])); std::vector<Val> noargs; return pyhp_rt_method(A[0], "values", noargs); }
    if (name == "items")  { need(1, 1); if (A[0].k != Val::DI) pyhp_rt_throw("TypeError", "items() expects a dict, got " + pyhp_rt_type_name(A[0])); std::vector<Val> noargs; return pyhp_rt_method(A[0], "items", noargs); }
    if (name == "list") {
        need(0, 1);
        if (A.empty()) return Val::mklist();
        return pyhp_rt_list(pyhp_rt_itervals(A[0]));
    }
    if (name == "dict") {
        need(0, 1);
        if (A.empty()) return Val::mkdict();
        if (A[0].k == Val::DI) { Val c = Val::mkdict(); *c.di = *A[0].di; return c; }
        if (A[0].k == Val::LI) {
            Val d = Val::mkdict();
            for (const Val& pair : *A[0].li) {
                if (pair.k != Val::LI || pair.li->size() != 2)
                    pyhp_rt_throw("ValueError", "dict() expects a list of [key, value] pairs");
                d.di->push_back({pyhp_rt_key_encode((*pair.li)[0]), (*pair.li)[1]});
            }
            return d;
        }
        pyhp_rt_throw("TypeError", "dict() expects a dict or a list of pairs, got " + pyhp_rt_type_name(A[0]));
    }
    if (name == "abs") {
        need(1, 1);
        if (A[0].k == Val::IN) return Val::mk((int64_t)(A[0].i < 0 ? -A[0].i : A[0].i));
        return Val::mk(std::fabs(pyhp_rt_num1(A[0], "abs")));
    }
    if (name == "min" || name == "max") {
        need(1, -1);
        std::vector<Val> vals;
        if (A.size() == 1) vals = pyhp_rt_itervals(A[0]);
        else vals = A;
        if (vals.empty()) pyhp_rt_throw("ValueError", name + "() of empty sequence");
        Val best = vals[0];
        for (const Val& v : vals) {
            int c = pyhp_rt_cmp(v, best, name == "min" ? "<" : ">");
            if ((name == "min" && c < 0) || (name == "max" && c > 0)) best = v;
        }
        return best;
    }
    if (name == "floor") { need(1, 1); return Val::mk((int64_t)std::floor(pyhp_rt_num1(A[0], "floor"))); }
    if (name == "ceil")  { need(1, 1); return Val::mk((int64_t)std::ceil(pyhp_rt_num1(A[0], "ceil"))); }
    if (name == "round") {
        need(1, 2);
        double x = pyhp_rt_num1(A[0], "round");
        int64_t p = A.size() > 1 ? pyhp_rt_int1(A[1], "round") : 0;
        if (p == 0) {
            double r = std::round(x);
            if (A[0].k == Val::IN) return Val::mk((int64_t)x); // PHP: round(int) keeps int
            return Val::mk((int64_t)r);
        }
        double m = std::pow(10.0, (double)p);
        return Val::mk(std::round(x * m) / m);
    }
    if (name == "sqrt") {
        need(1, 1);
        double x = pyhp_rt_num1(A[0], "sqrt");
        if (x < 0) pyhp_rt_throw("ValueError", "sqrt() of negative number");
        return Val::mk(std::sqrt(x));
    }
    if (name == "pow") { need(2, 2); return pyhp_rt_pow(A[0], A[1]); }
    if (name == "int")   { need(0, 1); return A.empty() ? Val::mk((int64_t)0) : Val::mk(pyhp_rt_int_conv(A[0])); }
    if (name == "float") { need(0, 1); return A.empty() ? Val::mk(0.0) : Val::mk(pyhp_rt_float_conv(A[0])); }
    if (name == "str")   { need(0, 1); return A.empty() ? Val::mk(std::string()) : Val::mk(pyhp_rt_tostr(A[0])); }
    if (name == "bool")  { need(0, 1); return A.empty() ? Val::mk(false) : Val::mk(pyhp_rt_truthy(A[0])); }
    if (name == "type")  { need(1, 1); return Val::mk(pyhp_rt_type_name(A[0])); }
    if (name == "chr") {
        need(1, 1);
        int64_t n = pyhp_rt_int1(A[0], "chr");
        if (n < 0 || n > 0x10FFFF) pyhp_rt_throw("ValueError", "chr() out of range: " + std::to_string(n));
        std::string o;
        if (n < 0x80) o.push_back((char)n);
        else if (n < 0x800) { o.push_back((char)(0xC0 | (n >> 6))); o.push_back((char)(0x80 | (n & 0x3F))); }
        else if (n < 0x10000) { o.push_back((char)(0xE0 | (n >> 12))); o.push_back((char)(0x80 | ((n >> 6) & 0x3F))); o.push_back((char)(0x80 | (n & 0x3F))); }
        else { o.push_back((char)(0xF0 | (n >> 18))); o.push_back((char)(0x80 | ((n >> 12) & 0x3F))); o.push_back((char)(0x80 | ((n >> 6) & 0x3F))); o.push_back((char)(0x80 | (n & 0x3F))); }
        return Val::mk(o);
    }
    if (name == "ord") {
        need(1, 1);
        const std::string& s = pyhp_rt_str1(A[0], "ord");
        if (s.empty()) pyhp_rt_throw("TypeError", "ord() expects a single-character string");
        unsigned char c0 = (unsigned char)s[0];
        int cp = c0;
        if (c0 >= 0xF0 && s.size() >= 4) cp = ((c0 & 0x07) << 18) | (((unsigned char)s[1] & 0x3F) << 12) | (((unsigned char)s[2] & 0x3F) << 6) | ((unsigned char)s[3] & 0x3F);
        else if (c0 >= 0xE0 && s.size() >= 3) cp = ((c0 & 0x0F) << 12) | (((unsigned char)s[1] & 0x3F) << 6) | ((unsigned char)s[2] & 0x3F);
        else if (c0 >= 0xC0 && s.size() >= 2) cp = ((c0 & 0x1F) << 6) | ((unsigned char)s[1] & 0x3F);
        return Val::mk((int64_t)cp);
    }
    if (name == "hex") {
        need(1, 1);
        int64_t n = pyhp_rt_bit_int(A[0], "hex()");
        std::string d;
        bool neg = n < 0;
        unsigned long long u = neg ? (unsigned long long)(-n) : (unsigned long long)n;
        if (u == 0) d = "0";
        while (u > 0) { d = "0123456789abcdef"[u & 15] + d; u >>= 4; }
        return Val::mk(std::string(neg ? "-0x" : "0x") + d);
    }
    if (name == "bin") {
        need(1, 1);
        int64_t n = pyhp_rt_bit_int(A[0], "bin()");
        std::string d;
        bool neg = n < 0;
        unsigned long long u = neg ? (unsigned long long)(-n) : (unsigned long long)n;
        if (u == 0) d = "0";
        while (u > 0) { d = (u & 1 ? "1" : "0") + d; u >>= 1; }
        return Val::mk(std::string(neg ? "-0b" : "0b") + d);
    }
    if (name == "sha256") { need(1, 1); return Val::mk(pyhp_rt_sha256(pyhp_rt_str1(A[0], "sha256"))); }
    if (name == "json_parse")  { need(1, 1); const char* p = pyhp_rt_str1(A[0], "json_parse").c_str(); Val v = pyhp_rt_json_parse(p); pyhp_rt_json_ws(p); if (*p != '\0') pyhp_rt_throw("ValueError", "json_parse(): invalid JSON — trailing data"); return v; }
    if (name == "json_string") { need(1, 1); std::string out; pyhp_rt_json_write(A[0], out); return Val::mk(out); }
    if (name == "base64e") { need(1, 1); return Val::mk(pyhp_rt_b64e(pyhp_rt_str1(A[0], "base64e"))); }
    if (name == "base64d") { need(1, 1); return Val::mk(pyhp_rt_b64d(pyhp_rt_str1(A[0], "base64d"))); }
    if (name == "urlenc")  { need(1, 1); return Val::mk(pyhp_rt_urlenc(pyhp_rt_str1(A[0], "urlenc"))); }
    if (name == "urldec")  { need(1, 1); return Val::mk(pyhp_rt_urldec(pyhp_rt_str1(A[0], "urldec"))); }
    if (name == "file_read") {
        need(1, 1);
        std::ifstream f(pyhp_rt_str1(A[0], "file_read"), std::ios::binary);
        if (!f) pyhp_rt_throw("RuntimeError", "cannot read file: " + pyhp_rt_str1(A[0], "file_read"));
        std::ostringstream ss;
        ss << f.rdbuf();
        return Val::mk(ss.str());
    }
    if (name == "file_write" || name == "file_append") {
        need(2, 2);
        std::ofstream f(pyhp_rt_str1(A[0], name.c_str()),
            std::ios::binary | (name == "file_write" ? std::ios::trunc : std::ios::app));
        if (!f) pyhp_rt_throw("RuntimeError", "cannot write file: " + pyhp_rt_str1(A[0], name.c_str()));
        f << pyhp_rt_tostr(A[1]);
        return Val::mk(true);
    }
    if (name == "file_exists") {
        need(1, 1);
        std::ifstream f(pyhp_rt_str1(A[0], "file_exists"));
        return Val::mk(f.good());
    }
    if (name == "argv") { need(0, 0); std::vector<Val> out; for (const auto& s : pyhp_rt_argv) out.push_back(Val::mk(s)); return pyhp_rt_list(std::move(out)); }
    if (name == "exit") {
        need(0, 1);
        int code = A.empty() ? 0 : (int)pyhp_rt_int1(A[0], "exit");
        std::fflush(stdout);
        std::exit(code);
    }
    if (name == "time") {
        need(0, 0);
        using namespace std::chrono;
        double s = (double)duration_cast<microseconds>(system_clock::now().time_since_epoch()).count();
        return Val::mk(s / 1000000.0);
    }
    pyhp_rt_throw("RuntimeError", "undefined function '" + name + "'");
}

static int64_t pyhp_rt_to_i(const Val& v, const std::string& fn) {
    if (v.k == Val::IN) return v.i;
    if (v.k == Val::FL && std::floor(v.f) == v.f) return (int64_t)v.f;
    pyhp_rt_throw("TypeError", fn + "() expects an int (int64_t) argument, got " + pyhp_rt_type_name(v));
    return 0;
}
static double pyhp_rt_to_d(const Val& v, const std::string& fn) {
    if (v.k == Val::IN) return (double)v.i;
    if (v.k == Val::FL) return v.f;
    pyhp_rt_throw("TypeError", fn + "() expects a number (double) argument, got " + pyhp_rt_type_name(v));
    return 0;
}
static std::string pyhp_rt_to_s(const Val& v, const std::string& fn) {
    if (v.k == Val::ST) return *v.s;
    pyhp_rt_throw("TypeError", fn + "() expects a string (const char*) argument, got " + pyhp_rt_type_name(v));
    return "";
}

/* ---------------- pyhp_list bridge (flat int/float/string/null items) --- */
enum PyHpVKind : unsigned char { PYHP_VN = 0, PYHP_VI = 1, PYHP_VF = 2, PYHP_VS = 3 };
struct pyhp_val { unsigned char kind; int64_t i; double f; const char* s; };
struct pyhp_list { int64_t len; pyhp_val* items; };

/* Convert a PyHP list value into C-bridge form. String items are strdup'd —
 * bridge lists own their strings; release with pyhp_list_free(). */
static pyhp_list pyhp_val_to_list(const Val& v, const char* fn) {
    if (v.k != Val::LI) pyhp_rt_throw("TypeError", std::string(fn) + "() expects a list (pyhp_list) argument");
    pyhp_list L;
    L.len = (int64_t)v.li->size();
    L.items = (pyhp_val*)std::malloc(sizeof(pyhp_val) * (size_t)(L.len > 0 ? L.len : 1));
    for (int64_t i = 0; i < L.len; i++) {
        const Val& e = (*v.li)[(size_t)i];
        pyhp_val pv; pv.kind = PYHP_VN; pv.i = 0; pv.f = 0.0; pv.s = nullptr;
        if (e.k == Val::IN) { pv.kind = PYHP_VI; pv.i = e.i; }
        else if (e.k == Val::FL) { pv.kind = PYHP_VF; pv.f = e.f; }
        else if (e.k == Val::ST) { pv.kind = PYHP_VS; pv.s = strdup(e.s->c_str()); }   // bridge lists own their strings
        L.items[i] = pv;
    }
    return L;
}

/* Materialise a C-bridge list (returned by a cpp export) as a PyHP list.
 * Strings are copied; then the C-side memory can be released. */
static Val pyhp_list_to_val(const pyhp_list& L) {
    Val out = Val::mklist();
    for (int64_t i = 0; i < L.len; i++) {
        const pyhp_val& p = L.items[i];
        if (p.kind == PYHP_VI) out.li->push_back(Val::mk(p.i));
        else if (p.kind == PYHP_VF) out.li->push_back(Val::mk(p.f));
        else if (p.kind == PYHP_VS) out.li->push_back(Val::mk(std::string(p.s ? p.s : "")));
        else out.li->push_back(Val::nul());
    }
    return out;
}

/* Release list memory allocated by the bridge (malloc'd items + strdup'd
 * strings — the ownership contract for lists a cpp export returns). */
static void pyhp_list_free(pyhp_list* L) {
    if (!L->items) return;
    for (int64_t i = 0; i < L->len; i++) {
        if (L->items[i].kind == PYHP_VS && L->items[i].s != nullptr) std::free((void*)L->items[i].s);
    }
    std::free(L->items);
    L->items = nullptr;
}

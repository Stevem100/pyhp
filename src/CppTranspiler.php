<?php
/**
 * PyHP -> C++17 transpiler (native backend).
 *
 * Emits a single self-contained C++17 source file implementing the PyHP value
 * model (aliasing lists/dicts, Python semantics) plus the user program.
 * Embedded `cpp { ... }` blocks are pasted verbatim and exported functions
 * become directly callable native code — no FFI, no PHP runtime.
 *
 *   pyhp build app.pyh --target cpp    -o app.cpp   # emit C++ source
 *   pyhp build app.pyh --target native -o app       # emit + g++ -> executable
 *
 * v1 limitations (documented in docs/REFERENCE.md):
 *   - lambdas capture enclosing values at creation (early binding);
 *     classes are not supported yet
 *   - try/finally is not supported yet (try/catch is)
 *   - a few host builtins (md5, sha256, ...) are unavailable
 */

require_once __DIR__ . '/runtime.php';

class PyHPCppTranspiler
{
    private int $tmpN = 0;
    private array $cppBlocks = [];       // raw cpp block sources (ordered)
    private array $cppExports = [];      // name => export info
    private array $modUnits = [];        // unit id => ['stmts'=>..., 'funcs'=>[name]]
    private array $modCache = [];        // realpath => unit id ('m1', ...)
    private array $modStack = [];        // cycle detection
    private int $modN = 0;
    private ?string $sourceDir = null;

    private const NATIVE_BUILTINS = [
        'print', 'println', 'repr', 'len', 'range', 'map', 'filter', 'zip', 'enumerate',
        'sorted', 'reversed', 'sum', 'any', 'all', 'keys', 'values', 'items',
        'list', 'dict', 'abs', 'min', 'max', 'floor', 'ceil', 'round', 'sqrt', 'pow',
        'int', 'float', 'str', 'bool', 'type', 'chr', 'ord', 'hex', 'bin',
        'json_parse', 'json_string', 'base64e', 'base64d', 'urlenc', 'urldec', 'sha256',
        'file_read', 'file_write', 'file_append', 'file_exists', 'argv', 'exit', 'time',
    ];

    public function setSourceFile(string $file): void {
        $rp = realpath($file);
        $this->sourceDir = $rp !== false ? dirname($rp) : dirname($file);
    }

    /* ================================================================ */
    /* entry                                                            */
    /* ================================================================ */

    public function transpile(array $stmts): string {
        $this->modUnits = [];
        $this->modCache = [];
        $this->modStack = [];
        $this->modN = 0;
        $this->cppBlocks = [];
        $this->cppExports = [];
        $this->tmpN = 0;

        $this->modUnits['main'] = ['stmts' => $stmts];
        $this->collectStmts($stmts);
        $this->collectExprs($stmts);

        $L = [];
        $L[] = '// Generated by PyHP ' . PYHP_VERSION . ' native backend — do not edit by hand.';
        $L[] = '// Build:  g++ -O2 -std=c++17 -o app app.cpp';
        $L[] = $this->rtCode();

        // global scope objects (declared before anything references them)
        $L[] = 'static PyScope pyhp_G;';
        foreach ($this->modUnits as $id => $u) {
            if ($id !== 'main') $L[] = 'static PyScope pyhp_' . $id . ';';
        }

        $this->emitCppSection($L);

        // forward declarations so definition order never matters
        foreach ($this->modUnits as $id => $u) {
            foreach ($u['funcs'] ?? [] as $name) {
                $L[] = 'static Val ' . $this->fnCName($id, $name) . '(std::vector<Val> __args);';
            }
        }
        foreach ($this->modUnits as $id => $u) {
            if ($id !== 'main') $L[] = 'static Val pyhp_rt_require_' . $id . '();';
        }
        $L[] = '';

        foreach ($this->modUnits as $id => $u) {
            if ($id === 'main') continue;
            $this->emitUnitFunctions($id, $u, $L);
        }
        $this->emitUnitFunctions('main', $this->modUnits['main'], $L);
        foreach ($this->modUnits as $id => $u) {
            if ($id !== 'main') $this->emitModuleInit($id, $u, $L);
        }
        $this->emitMain($this->modUnits['main']['stmts'], $L);
        return implode("\n", $L) . "\n";
    }

    /* ================================================================ */
    /* collection pass                                                  */
    /* ================================================================ */

    private function collectStmts(array $stmts): void {
        foreach ($stmts as $s) {
            switch ($s['k']) {
                case 'Expr':
                    if ($s['e']['k'] === 'Assign') { $this->collectAssignTarget($s['e']['target']); }
                    break;
                case 'VarDecl':
                    $this->modUnits[$this->curUnit]['assigned'][$s['name']] = true;
                    break;
                case 'Foreach':
                    $this->modUnits[$this->curUnit]['assigned'][$s['var1']] = true;
                    if ($s['var2'] !== null) $this->modUnits[$this->curUnit]['assigned'][$s['var2']] = true;
                    break;
                case 'Cpp':
                    $this->cppBlocks[] = $s['code'];
                    foreach ($s['exports'] as $e) {
                        if (isset($this->cppExports[$e['name']]) && $this->cppExports[$e['name']]['decl'] !== $e['decl']) {
                            throw new PyHPSyntaxError("line {$s['line']}: native export '{$e['name']}' declared twice with different signatures");
                        }
                        $this->cppExports[$e['name']] = $e;
                    }
                    break;
                case 'Func':
                    if ($s['name'] === null) {
                        $this->w($L, $ind, $this->emitNativeLambda($s, $sc) . ';');
                        break;
                    }
                    $this->modUnits[$this->curUnit]['funcs'][$s['name']] = true;
                    break;
                case 'Class':
                    $this->err('classes are not supported by the native backend yet — use the PHP engines (pyhp build --target php)', $s['line']);
                    break;
                case 'If':
                    foreach ($s['branches'] as [$c, $b]) { $this->collectStmts($b['stmts']); }
                    if ($s['else'] !== null) $this->collectStmts($s['else']['stmts']);
                    break;
                case 'While': case 'DoWhile': case 'For': case 'Foreach':
                    $this->collectStmts($s['body']['stmts']);
                    break;
                case 'Try':
                    $this->collectStmts($s['body']['stmts']);
                    foreach ($s['catches'] as $c) { $this->collectStmts($c['body']['stmts']); }
                    if ($s['finally'] !== null) {
                        $this->err("'finally' is not supported by the native backend yet (try/catch is)", $s['line']);
                    }
                    break;
                case 'Block':
                    $this->collectStmts($s['stmts']);
                    break;
            }
        }
    }

    private string $curUnit = 'main';

    private function collectExprs(array $stmts): void {
        foreach ($stmts as $s) {
            switch ($s['k']) {
                case 'Expr': $this->collectExpr($s['e']); break;
                case 'VarDecl': if ($s['init'] !== null) $this->collectExpr($s['init']); break;
                case 'Return': if ($s['e'] !== null) $this->collectExpr($s['e']); break;
                case 'Echo': foreach ($s['args'] as $a) { $this->collectExpr($a); } break;
                case 'Throw': $this->collectExpr($s['e']); break;
                case 'If':
                    foreach ($s['branches'] as [$c, $b]) { $this->collectExpr($c); $this->collectExprs($b['stmts']); }
                    if ($s['else'] !== null) $this->collectExprs($s['else']['stmts']);
                    break;
                case 'While': $this->collectExpr($s['cond']); $this->collectExprs($s['body']['stmts']); break;
                case 'DoWhile': $this->collectExpr($s['cond']); $this->collectExprs($s['body']['stmts']); break;
                case 'For':
                    if ($s['init'] !== null) $this->collectExprs([$s['init']]);
                    if ($s['cond'] !== null) $this->collectExpr($s['cond']);
                    if ($s['update'] !== null) $this->collectExpr($s['update']);
                    $this->collectExprs($s['body']['stmts']);
                    break;
                case 'Foreach':
                    $this->collectExpr($s['iter']);
                    $this->collectExprs($s['body']['stmts']);
                    break;
                case 'Try':
                    $this->collectExprs($s['body']['stmts']);
                    foreach ($s['catches'] as $c) { $this->collectExprs($c['body']['stmts']); }
                    break;
                case 'Block': $this->collectExprs($s['stmts']); break;
                case 'Cpp': break;
            }
        }
    }

    private function collectAssignTarget(array $t): void {
        if ($t['k'] === 'Var') { $this->modUnits[$this->curUnit]['assigned'][$t['name']] = true; }
        elseif ($t['k'] === 'Idx') { $this->collectAssignTarget($t['obj']); }
        elseif ($t['k'] === 'Member') { $this->collectAssignTarget($t['obj']); }
    }

    private function collectExpr(array $e): void {
        switch ($e['k']) {
            case 'Call':
                $args = $e['args'];
                // require("unit") pulls in a new module at collect time
                if ($e['callee']['k'] === 'Var' && $e['callee']['name'] === 'require'
                    && count($args) === 1 && $args[0]['k'] === 'Str') {
                    $this->collectRequire($args[0]['v'], $e['line']);
                }
                $this->collectExpr($e['callee']);
                foreach ($args as $a) { $this->collectExpr($a); }
                break;
            case 'FStr':
                foreach ($e['parts'] as $p) { if ($p[0] === 'e') $this->collectExpr($p[1]); }
                break;
            case 'List': foreach ($e['items'] as $i) { $this->collectExpr($i); } break;
            case 'Dict': foreach ($e['pairs'] as [$k, $v]) { $this->collectExpr($k); $this->collectExpr($v); } break;
            case 'Comp':
                $this->collectExpr($e['iter']);
                if ($e['key'] !== null) $this->collectExpr($e['key']);
                $this->collectExpr($e['val']);
                if ($e['cond'] !== null) $this->collectExpr($e['cond']);
                break;
            case 'Bin': $this->collectExpr($e['l']); $this->collectExpr($e['r']); break;
            case 'Un': $this->collectExpr($e['e']); break;
            case 'Post': $this->collectExpr($e['e']); break;
            case 'Ternary': $this->collectExpr($e['c']); $this->collectExpr($e['a']); $this->collectExpr($e['b']); break;
            case 'Idx': $this->collectExpr($e['obj']); $this->collectExpr($e['idx']); break;
            case 'Slice':
                $this->collectExpr($e['obj']);
                foreach (['start', 'stop', 'step'] as $p) { if ($e[$p] !== null) $this->collectExpr($e[$p]); }
                break;
            case 'Member': $this->collectExpr($e['obj']); break;
            case 'Assign':
                $this->collectExpr($e['target']);
                $this->collectExpr($e['value']);
                break;
            case 'Func':
                foreach ($e['params'] as $p) {
                    if (($p['def'] ?? null) !== null) $this->collectExpr($p['def']);
                }
                $this->collectExprs($e['body']['stmts']);
                break;
            case 'Var': case 'Num': case 'Str': case 'Bool': case 'Null': case 'This': case 'Super':
                break;
        }
    }

    private function collectRequire(string $spec, int $line): void {
        $path = $this->resolveModule($spec, $line);
        $rp = realpath($path);
        if (isset($this->modCache[$rp])) return;
        if (in_array($rp, $this->modStack, true)) {
            throw new PyHPSyntaxError("circular module dependency: '{$spec}'");
        }
        $id = 'm' . (++$this->modN);
        $this->modCache[$rp] = $id;
        $this->modStack[] = $rp;
        $stmts = PyHPParser::parseSource((string)file_get_contents($path));
        $saved = $this->curUnit;
        $this->curUnit = $id;
        $this->modUnits[$id] = ['stmts' => $stmts, 'path' => $path];
        $this->collectStmts($stmts);
        $this->collectExprs($stmts);
        $this->curUnit = $saved;
        array_pop($this->modStack);
    }

    private function resolveModule(string $spec, int $line): string {
        $path = pyhp_resolve_module($spec, (string)($this->sourceDir ?? '.'));
        if ($path !== null) return $path;
        $this->err("ModuleNotFoundError: cannot find module '{$spec}'", $line);
    }

    /* ================================================================ */
    /* helpers                                                          */
    /* ================================================================ */

    private function tmp(): string { return '__t' . (++$this->tmpN); }

    private function fnCName(string $unit, string $name): string {
        return ($unit === 'main' ? 'pyhp_fn_' : 'pyhp_' . $unit . '_fn_') . $this->cppIdent($name);
    }

    private function cppIdent(string $name): string {
        $n = preg_replace('/[^A-Za-z0-9_]/', '_', $name);
        if ($n === '' || ctype_digit($n[0])) $n = '_' . $n;
        return $n;
    }

    private function cppStr(string $s): string {
        $out = '"';
        $n = strlen($s);
        for ($i = 0; $i < $n; $i++) {
            $c = $s[$i];
            switch ($c) {
                case "\\": $out .= '\\\\'; break;
                case '"':  $out .= '\\"'; break;
                case "\n": $out .= '\\n'; break;
                case "\t": $out .= '\\t'; break;
                case "\r": $out .= '\\r'; break;
                default:
                    $o = ord($c);
                    if ($o < 32 || $o > 126) $out .= sprintf('\\%03o', $o);
                    else $out .= $c;
            }
        }
        return $out . '"';
    }

    private function cppNum($v): string {
        if (is_int($v)) return '(int64_t)' . $v . 'LL';
        return json_encode($v, JSON_PRESERVE_ZERO_FRACTION);
    }

    private function err(string $msg, int $line): void {
        throw new PyHPSyntaxError("line {$line}: {$msg} (native backend)");
    }

    /* ================================================================ */
    /* cpp section                                                      */
    /* ================================================================ */

    private function emitCppSection(array &$L): void {
        if (count($this->cppBlocks) === 0) return;
        $includes = [];
        $bodies = [];
        foreach ($this->cppBlocks as $code) {
            $inc = [];
            $body = [];
            foreach (preg_split('/\r?\n/', $code) as $line) {
                $t = ltrim($line);
                if (str_starts_with($t, '#include') || str_starts_with($t, '# include')) { $inc[] = $line; continue; }
                $body[] = $line;
            }
            $includes[] = implode("\n", $inc);
            $bodies[] = implode("\n", $body);
        }
        $L[] = '';
        $L[] = '/* ---------- embedded cpp { ... } blocks ---------- */';
        foreach (array_filter($includes) as $inc) { $L[] = $inc; }
        $L[] = '#ifdef __cplusplus';
        $L[] = 'extern "C" {';
        $L[] = '#endif';
        foreach ($bodies as $b) { $L[] = $b; }
        $L[] = '#ifdef __cplusplus';
        $L[] = '}';
        $L[] = '#endif';
        $L[] = '';
        $L[] = '/* ---------- native export dispatch ---------- */';
        foreach ($this->cppExports as $name => $e) {
            $L[] = 'extern "C" ' . $e['decl'] . ';';
        }
        $L[] = 'static Val pyhp_rt_native(const std::string& name, std::vector<Val> A) {';
        foreach ($this->cppExports as $name => $e) {
            [$kinds, $ret] = self::sigKinds($e);
            $conv = [];
            $call = [];
            $listIdx = [];
            for ($i = 0; $i < count($kinds); $i++) {
                switch ($kinds[$i]) {
                    case 'i': $conv[] = "    int64_t a{$i} = pyhp_rt_to_i(A[{$i}], {$this->cppStr($name)});"; break;
                    case 'd': $conv[] = "    double a{$i} = pyhp_rt_to_d(A[{$i}], {$this->cppStr($name)});"; break;
                    case 's': $conv[] = "    std::string ss{$i} = pyhp_rt_to_s(A[{$i}], {$this->cppStr($name)});"; break;
                    case 'l': $conv[] = "    pyhp_list a{$i} = pyhp_val_to_list(A[{$i}], " . $this->cppStr($name) . ");"; $listIdx[] = $i; break;
                }
                $call[] = $kinds[$i] === 's' ? "ss{$i}.c_str()" : "a{$i}";
            }
            $callStr = implode(', ', $call);
            $freeLines = implode('', array_map(fn($i) => "    pyhp_list_free(&a{$i});\n", $listIdx));
            $L[] = '    if (name == ' . $this->cppStr($name) . ') {';
            if (count($kinds) > 0) {
                $L[] = '        if (A.size() != ' . count($kinds) . ') pyhp_rt_throw("TypeError", std::string(' . $this->cppStr($name) . ') + "() wrong number of arguments");';
            }
            foreach ($conv as $c) { $L[] = $c; }
            switch ($ret) {
                case 'i': $L[] = "        int64_t __r = {$name}({$callStr});\n{$freeLines}        return Val::mk(__r);"; break;
                case 'd': $L[] = "        double __r = {$name}({$callStr});\n{$freeLines}        return Val::mk(__r);"; break;
                case 's': $L[] = "        { const char* __r = {$name}({$callStr}); std::string __s(__r ? __r : \"\"); {$freeLines} return Val::mk(__s); }"; break;
                case 'l': $L[] = "        { pyhp_list __r = {$name}({$callStr}); Val __v = pyhp_list_to_val(__r); pyhp_list_free(&__r); {$freeLines} return __v; }"; break;
                default:  $L[] = "        {$name}({$callStr});\n{$freeLines}        return Val::nul();";
            }
            $L[] = '    }';
        }
        $L[] = '    pyhp_rt_throw("RuntimeError", "native function \'" + name + "\' is not exported by any cpp block");';
        $L[] = '}';
    }

    /** @return array{0: string[], 1: string} [param kinds, return kind] */
    private static function sigKinds(array $e): array {
        $params = trim($e['params']);
        $kinds = [];
        if ($params !== '' && strtolower($params) !== 'void') {
            foreach (explode(',', $params) as $p) {
                $t = trim($p);
                $t = preg_replace('/\s+[A-Za-z_][A-Za-z0-9_]*$/', '', $t);
                $kinds[] = pyhp_cpp_type_kind($t);
            }
        }
        return [$kinds, pyhp_cpp_type_kind($e['ret'])];
    }

    /* ================================================================ */
    /* statement emission                                               */
    /* ================================================================ */

    private function w(array &$L, int $ind, string $line): void {
        $L[] = str_repeat('    ', $ind) . $line;
    }

    private function emitUnitFunctions(string $unit, array $u, array &$L): void {
        $saved = $this->curUnitEmit;
        $this->curUnitEmit = $unit;
        foreach ($u['stmts'] as $s) {
            if ($s['k'] === 'Func' && $s['name'] !== null) {
                $this->emitFunction($unit, $s, $L);
                $L[] = '';
            }
        }
        $this->curUnitEmit = $saved;
    }

    private function emitFunction(string $unit, array $s, array &$L): void {
        $label = $s['name'];
        $savedParams = $this->curFnParams;
        $this->curFnParams = [];
        foreach ($s['params'] as $p) { $this->curFnParams[$p['name']] = true; }
        $nNamed = 0;
        $variadic = false;
        foreach ($s['params'] as $p) { if ($p['variadic']) $variadic = true; else $nNamed++; }
        $L[] = 'static Val ' . $this->fnCName($unit, $s['name']) . '(std::vector<Val> __args) {';
        $L[] = '    PyScope env(&' . ($unit === 'main' ? 'pyhp_G' : 'pyhp_' . $unit) . ');';
        if (!$variadic) {
            $L[] = '    if (__args.size() > ' . $nNamed . ') pyhp_rt_throw("TypeError", ' . $this->cppStr("{$label}() takes {$nNamed} argument(s), ") . ' + std::to_string(__args.size()) + " given");';
        }
        $i = 0;
        foreach ($s['params'] as $p) {
            if ($p['variadic']) {
                $this->w($L, 1, 'env.declare(' . $this->cppStr($p['name']) . ', pyhp_rt_rest(__args, ' . $i . '));');
                break;
            }
            if ($p['def'] !== null) {
                $this->w($L, 1, 'env.declare(' . $this->cppStr($p['name']) . ', (__args.size() > ' . $i . ') ? __args[' . $i . '] : ' . $this->emitExpr($p['def'], 'env') . ');');
            } else {
                $L[] = '    if (__args.size() <= ' . $i . ') pyhp_rt_throw("TypeError", ' . $this->cppStr("{$label}() missing required argument '{$p['name']}'") . ');';
                $L[] = '    env.declare(' . $this->cppStr($p['name']) . ', __args[' . $i . ']);';
            }
            $i++;
        }
        $this->emitStmts($s['body']['stmts'], 'env', $L, 1);
        $L[] = '    return Val::nul();';
        $L[] = '}';
        $this->curFnParams = $savedParams;
    }

    private function emitModuleInit(string $unit, array $u, array &$L): void {
        $L[] = 'static Val pyhp_rt_require_' . $unit . '() {';
        $L[] = '    static bool __done = false;';
        $L[] = '    static Val __table;';
        $L[] = '    if (__done) return __table;';
        $L[] = '    __done = true;';
        $L[] = '    PyScope env(&pyhp_' . $unit . ');';
        $top = [];
        foreach ($u['stmts'] as $s) {
            if ($s['k'] === 'Func') continue;
            $top[] = $s;
        }
        $this->emitStmts($top, 'env', $L, 1);
        $L[] = '    __table = Val::mkdict();';
        foreach ($u['stmts'] as $s) {
            if ($s['k'] === 'Func' && $s['name'] !== null) {
                $L[] = '    __table.di->push_back({' . $this->cppStr($s['name']) . ', pyhp_rt_wrapfn(' . $this->cppStr($s['name']) . ', &' . $this->fnCName($unit, $s['name']) . ')});';
            }
        }
        $L[] = '    return __table;';
        $L[] = '}';
        $L[] = '';
    }

    private function emitMain(array $stmts, array &$L): void {
        $top = [];
        foreach ($stmts as $s) {
            if ($s['k'] === 'Func' && $s['name'] !== null) continue;
            $top[] = $s;
        }
        $L[] = 'static void pyhp_main() {';
        $L[] = '    PyScope env(&pyhp_G);';
        $this->emitStmts($top, 'env', $L, 1);
        $L[] = '}';
        $L[] = '';
        $L[] = 'int main(int argc, char** argv) {';
        $L[] = '    pyhp_rt_set_argv(argc, argv);';
        $L[] = '    try {';
        $L[] = '        pyhp_main();';
        $L[] = '    } catch (PyError& __e) {';
        $L[] = '        std::fflush(stdout);';
        $L[] = '        std::fprintf(stderr, "PyHP %s: %s\\n", __e.type.c_str(), __e.what());';
        $L[] = '        return 1;';
        $L[] = '    }';
        $L[] = '    std::fflush(stdout);';
        $L[] = '    return 0;';
        $L[] = '}';
    }

    private function emitStmts(array $stmts, string $sc, array &$L, int $ind): void {
        foreach ($stmts as $s) { $this->emitStmt($s, $sc, $L, $ind); }
    }

    private function emitStmt(array $s, string $sc, array &$L, int $ind): void {
        switch ($s['k']) {
            case 'Expr':
                $this->w($L, $ind, $this->emitExpr($s['e'], $sc) . ';');
                return;
            case 'VarDecl':
                $name = $s['name'];
                if ($s['init'] !== null) {
                    $v = $this->emitExpr($s['init'], $sc);
                    if ($s['type'] !== null && $s['type'] !== 'var') {
                        $v = "pyhp_rt_checktype({$v}, " . $this->cppStr($s['type']) . ', ' . $this->cppStr($name) . ')';
                    }
                    $this->w($L, $ind, "{$sc}.declare(" . $this->cppStr($name) . ", {$v});");
                } else {
                    $this->w($L, $ind, "{$sc}.declare(" . $this->cppStr($name) . ', Val::nul());');
                }
                return;
            case 'Echo': {
                $parts = array_map(fn($a) => 'pyhp_rt_tostr(' . $this->emitExpr($a, $sc) . ')', $s['args']);
                $this->w($L, $ind, 'std::fputs((' . (implode(' + ', $parts) ?: '""') . ').c_str(), stdout);');
                return;
            }
            case 'If': {
                $first = true;
                foreach ($s['branches'] as [$cond, $body]) {
                    $kw = $first ? 'if' : '} else if';
                    $this->w($L, $ind, ($first ? 'if' : $kw) . ' (pyhp_rt_truthy(' . $this->emitExpr($cond, $sc) . ')) {');
                    $first = false;
                    $this->emitStmts($body['stmts'], $sc, $L, $ind + 1);
                }
                if ($s['else'] !== null) {
                    $this->w($L, $ind, '} else {');
                    $this->emitStmts($s['else']['stmts'], $sc, $L, $ind + 1);
                }
                $this->w($L, $ind, '}');
                return;
            }
            case 'While':
                $this->w($L, $ind, 'while (pyhp_rt_truthy(' . $this->emitExpr($s['cond'], $sc) . ')) {');
                $this->emitStmts($s['body']['stmts'], $sc, $L, $ind + 1);
                $this->w($L, $ind, '}');
                return;
            case 'DoWhile':
                $this->w($L, $ind, 'do {');
                $this->emitStmts($s['body']['stmts'], $sc, $L, $ind + 1);
                $this->w($L, $ind, '} while (pyhp_rt_truthy(' . $this->emitExpr($s['cond'], $sc) . '));');
                return;
            case 'For':
                if ($s['init'] !== null) {
                    $this->emitStmt($s['init'], $sc, $L, $ind); // PyHP leaks for-vars, so init goes outside the loop
                }
                $cond = $s['cond'] === null ? '' : 'pyhp_rt_truthy(' . $this->emitExpr($s['cond'], $sc) . ')';
                $upd = $s['update'] === null ? '' : $this->emitExpr($s['update'], $sc);
                $this->w($L, $ind, "for (; {$cond}; {$upd}) {");
                $this->emitStmts($s['body']['stmts'], $sc, $L, $ind + 1);
                $this->w($L, $ind, '}');
                return;
            case 'Foreach': {
                $it = $this->tmp();
                $this->w($L, $ind, 'for (auto& __kv : pyhp_rt_pairs(' . $this->emitExpr($s['iter'], $sc) . ')) {');
                if ($s['var2'] !== null) {
                    $this->w($L, $ind + 1, "{$sc}.declare(" . $this->cppStr($s['var1']) . ', __kv.first);');
                    $this->w($L, $ind + 1, "{$sc}.declare(" . $this->cppStr($s['var2']) . ', __kv.second);');
                } else {
                    $this->w($L, $ind + 1, "{$sc}.declare(" . $this->cppStr($s['var1']) . ', __kv.second);');
                }
                $this->emitStmts($s['body']['stmts'], $sc, $L, $ind + 1);
                $this->w($L, $ind, '}');
                return;
            }
            case 'Try': {
                $this->w($L, $ind, 'try {');
                $this->emitStmts($s['body']['stmts'], $sc, $L, $ind + 1);
                $this->w($L, $ind, '} catch (PyError& __e) {');
                $first = true;
                foreach ($s['catches'] as $c) {
                    $cond = $c['type'] === null ? 'true' : 'pyhp_rt_catch_match(__e, ' . $this->cppStr($c['type']) . ')';
                    $this->w($L, $ind + 1, ($first ? 'if' : '} else if') . ' (' . $cond . ') {');
                    $this->w($L, $ind + 2, "{$sc}.declare(" . $this->cppStr($c['var']) . ', pyhp_rt_errval(__e));');
                    $this->emitStmts($c['body']['stmts'], $sc, $L, $ind + 2);
                    $first = false;
                }
                if (!$first) {
                    $this->w($L, $ind + 1, '} else { throw; }');
                } else {
                    $this->w($L, $ind + 1, 'throw;');
                }
                $this->w($L, $ind, '}');
                return;
            }
            case 'Throw':
                $e = $s['e'];
                if ($e['k'] === 'Call' && $e['callee']['k'] === 'Var'
                    && in_array($e['callee']['name'], ['Exception', 'TypeError', 'ValueError', 'KeyError', 'IndexError', 'ZeroDivisionError', 'MemError', 'RuntimeError'], true)
                    && count($e['args']) <= 1) {
                    $msg = count($e['args']) === 1 ? 'pyhp_rt_tostr(' . $this->emitExpr($e['args'][0], $sc) . ')' : '""';
                    $this->w($L, $ind, 'pyhp_rt_throw(' . $this->cppStr($e['callee']['name']) . ', ' . $msg . ');');
                    return;
                }
                $this->w($L, $ind, 'pyhp_rt_throw("RuntimeError", pyhp_rt_tostr(' . $this->emitExpr($e, $sc) . '));');
                return;
            case 'Return':
                $this->w($L, $ind, 'return ' . ($s['e'] === null ? 'Val::nul()' : $this->emitExpr($s['e'], $sc)) . ';');
                return;
            case 'Break':
                $this->w($L, $ind, 'break;');
                return;
            case 'Continue':
                $this->w($L, $ind, 'continue;');
                return;
            case 'Block':
                $this->w($L, $ind, '{');
                $this->emitStmts($s['stmts'], $sc, $L, $ind + 1);
                $this->w($L, $ind, '}');
                return;
            case 'Cpp':
                return; // collected & emitted in the cpp section
            case 'Func':
                if ($s['name'] !== null) return; // hoisted
                foreach ($s['params'] as $p) {
                    if (($p['def'] ?? null) !== null) $this->collectExpr($p['def']);
                }
                $this->collectExprs($s['body']['stmts']);
                return;
            case 'Class':
                $this->err('classes are not supported by the native backend yet — use the PHP engines', $s['line']);
        }
        $this->err("unsupported statement '{$s['k']}'", $s['line']);
    }


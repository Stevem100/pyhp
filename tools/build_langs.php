<?php
/**
 * Generate docs/BRIDGE.md from src/langdata.php (the same data `pyhp langs`
 * serves offline). Run from the repo root:  php tools/build_langs.php
 */

require __DIR__ . '/../src/langdata.php';

$out = [];
$out[] = '<!-- Generated by tools/build_langs.php from src/langdata.php — do not edit by hand. -->';
$out[] = '';
$out[] = '# The PyHP bridge — one table across five languages';
$out[] = '';
$out[] = 'PyHP gives you PHP syntax with Python semantics. This reference maps the';
$out[] = 'everyday constructs to their Python, PHP, C++ and JavaScript equivalents so';
$out[] = 'you can read/write PyHP (or port code in any direction) without installing';
$out[] = 'those other runtimes — PyHP itself needs only PHP.';
$out[] = '';
$out[] = 'The same tables are available offline from the CLI: `pyhp langs [python|php|cpp|js|full]`.';
$out[] = '';

$data = pyhp_langs_data();
$rowCount = 0;
foreach ($data as $section => $entries) {
    $out[] = '## ' . $section;
    $out[] = '';
    $out[] = '| | PyHP | Python | PHP | C++ | JavaScript |';
    $out[] = '|---|---|---|---|---|---|';
    foreach ($entries as [$topic, $pyhp, $python, $php, $cpp, $js]) {
        $esc = fn($s) => str_replace('|', '\\|', $s);
        $out[] = "| {$esc($topic)} | `{$esc($pyhp)}` | `{$esc($python)}` | `{$esc($php)}` | `{$esc($cpp)}` | `{$esc($js)}` |";
        $rowCount++;
    }
    $out[] = '';
}

$out[] = "---";
$out[] = '';
$out[] = "{$rowCount} entries. Notes:";
$out[] = '';
$out[] = '- PyHP strings/lists/dicts behave like Python (`.upper()`, slicing with';
$out[] = '  steps, dict `.get()`, aliasing on assignment) even though the syntax is PHP.';
$out[] = '- Integer arithmetic promotes to arbitrary-precision automatically, like';
$out[] = '  Python — `2 ** 100` is exact on the PHP engines.';
$out[] = '- `range`/`map`/`filter`/`zip`/`enumerate`/`reversed` return lazy views (like';
$out[] = '  Python); wrap in `list(...)` when you need a materialised list.';
$out[] = '';

file_put_contents(__DIR__ . '/../docs/BRIDGE.md', implode("\n", $out) . "\n");
echo "docs/BRIDGE.md written ({$rowCount} entries)\n";
